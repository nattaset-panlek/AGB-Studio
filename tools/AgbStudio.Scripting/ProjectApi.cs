    /// <summary>agb_prelude.hpp: includes and helpers shared by all translated scripts.</summary>
    public static string Prelude(ScriptCompileContext ctx)
    {
        var sb = new StringBuilder();
        sb.Append("// Generated by AGB Studio. Do not edit. Included by every translated C# script.\n#pragma once\n");
        sb.Append("#include \"agb/api.hpp\"\n#include \"agb/behaviours.hpp\"\n#include \"agb/memory.hpp\"\n#include \"agb/natives.hpp\"\n#include \"agb/script.hpp\"\n");
        // C# debugging (D-21): AGB_SCOPE at method entry, AGB_PROBE before each statement; nothing in Release.
        sb.Append("#include \"agb/probe.hpp\"\n");
        sb.Append("#include \"agb_game.hpp\"\n");
        if (ctx.Sounds.Count + ctx.Music.Count > 0) sb.Append("#if __has_include(\"soundbank.hpp\")\n#include \"soundbank.hpp\"\n#endif\n");
        // SFX Designer effects on the DMG channels (GameBuilder writes their ids next to the soundbank's).
        sb.Append("#if __has_include(\"agb_dmg.hpp\")\n#include \"agb_dmg.hpp\"\n#endif\n");
        if (ctx.Tables.Count > 0) sb.Append("#include \"agb_db.hpp\"\n");
        sb.Append("""

            // C# array.Length
            template <typename T, int N>
            constexpr int agb_countof(T (&)[N]) { return N; }

            // Bitset save fields (unsigned char arrays in GameState).
            template <int N>
            inline bool agb_bit_get(const unsigned char (&b)[N], int i) { return i >= 0 && i < N * 8 && ((b[i >> 3] >> (i & 7)) & 1); }
            template <int N>
            inline void agb_bit_set(unsigned char (&b)[N], int i, bool v) {
                if (i < 0 || i >= N * 8) return;
                if (v) b[i >> 3] = static_cast<unsigned char>(b[i >> 3] | (1 << (i & 7)));
                else b[i >> 3] = static_cast<unsigned char>(b[i >> 3] & ~(1 << (i & 7)));
            }
            template <int N>
            constexpr int agb_bit_size(const unsigned char (&)[N]) { return N * 8; }
            template <int N>
            inline int agb_bit_count(const unsigned char (&b)[N]) {
                int n = 0;
                for (int i = 0; i < N; ++i)
                    for (int k = 0; k < 8; ++k) n += (b[i] >> k) & 1;
                return n;
            }

            // Debug.Log($"{speed}") for fixed values: "1.50", "-0.25" (two decimals, four rotating buffers).
            inline const char* agb_fixed_str(agb::fixed v) {
                static char buffers[4][16];
                static int next = 0;
                char* out = buffers[next];
                next = (next + 1) & 3;
                agb::s32 raw = v.raw;
                int p = 0;
                if (raw < 0) {
                    out[p++] = '-';
                    raw = -raw;
                }
                agb::s32 whole = raw >> 8;
                const agb::s32 hundredths = ((raw & 255) * 100 + 128) >> 8;
                char digits[12];
                int n = 0;
                do {
                    digits[n++] = static_cast<char>('0' + whole % 10);
                    whole /= 10;
                } while (whole && n < 11);
                while (n) out[p++] = digits[--n];
                out[p++] = '.';
                out[p++] = static_cast<char>('0' + (hundredths >= 100 ? 9 : hundredths / 10));
                out[p++] = static_cast<char>('0' + (hundredths >= 100 ? 9 : hundredths % 10));
                out[p] = 0;
                return out;
            }

            // Calling a [Cutscene] method from translated code starts it in the Event Script VM.
            template <typename... A>
            inline int agb_start_script(agb::u16 id, A... a) {
                const agb::s32 args[sizeof...(A) + 1] = {static_cast<agb::s32>(a)..., 0};
                return agb::script::start(id, agb::script::Priority::Cutscene, args, static_cast<int>(sizeof...(A)));
            }
            // [Cutscene(Background = ..., Once = ...)]: once is the key a second start is refused for while the first runs, or -1.
            template <typename... A>
            inline int agb_start_script_as(agb::script::Priority priority, agb::s32 once, agb::u16 id, A... a) {
                const agb::s32 args[sizeof...(A) + 1] = {static_cast<agb::s32>(a)..., 0};
                return agb::script::start(id, priority, args, static_cast<int>(sizeof...(A)), once);
            }

            """.Replace("\r\n", "\n"));
        if (ctx.Enums.Count > 0)
        {
            sb.Append("namespace agbgen {\n");
            foreach (var e in ctx.Enums)
                sb.Append($"enum class {BuildCpp.Ident(e.Name)} : agb::s32 {{ {string.Join(", ", e.Values.Select(BuildCpp.Ident))} }};\n");
            sb.Append("}  // namespace agbgen\n");
        }
        var shops = ctx.Tables.Select((t, i) => (t, i)).Where(x => HasShop(ctx, x.t)).ToList();
        if (shops.Count > 0)
        {
            var money = BuildCpp.Ident(ctx.ShopCurrencyField);
            sb.Append("namespace agbgen {\n");
            foreach (var (t, i) in shops)
            {
                var cls = BuildCpp.Ident(t.Name);
                sb.Append($"inline bool shopBuy_{cls}(agb_db::{DatabaseCodegen.IdEnum(t.Name)} id) {{\n");
                sb.Append($"    const int price = agb_db::{cls}::Get(id).price;\n");
                sb.Append($"    if (agb_state.{money} < price) return false;\n");
                sb.Append($"    agb_state.{money} -= price;\n");
                sb.Append($"    agb::script::natives::giveItem({i}, static_cast<agb::s32>(id), 1);\n    return true;\n}}\n");
            }
            sb.Append("}  // namespace agbgen\n");
        }
        return sb.ToString();
    }

