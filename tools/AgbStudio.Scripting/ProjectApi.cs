/// <summary>
/// The project part of the scripting API, generated from the project settings: <c>Game</c> (save fields),
/// database tables (<c>Items.Get(ItemId.Potion)</c>), name constants (<c>Songs.Help</c>, <c>Path.EnterScene</c>),
/// typed script variables (<c>Story.Forest</c>) and the C++ prelude every translated script includes.
/// </summary>
public static class ProjectApi
{
    public const string CSharpFileName = "GBA.Project.g.cs";

    static readonly HashSet<string> s_csKeywords = new(StringComparer.Ordinal)
    {
        "abstract", "as", "base", "bool", "break", "byte", "case", "catch", "char", "checked", "class", "const", "continue", "decimal",
        "default", "delegate", "do", "double", "else", "enum", "event", "explicit", "extern", "false", "finally", "fixed", "float", "for",
        "foreach", "goto", "if", "implicit", "in", "int", "interface", "internal", "is", "lock", "long", "namespace", "new", "null", "object",
        "operator", "out", "override", "params", "private", "protected", "public", "readonly", "ref", "return", "sbyte", "sealed", "short",
        "sizeof", "stackalloc", "static", "string", "struct", "switch", "this", "throw", "true", "try", "typeof", "uint", "ulong", "unchecked",
        "unsafe", "ushort", "using", "virtual", "void", "volatile", "while",
    };

    /// <summary>C# identifier for a project name (keywords get @).</summary>
    public static string CsIdent(string name)
    {
        var id = Names.Identifier(name);
        return s_csKeywords.Contains(id) ? "@" + id : id;
    }

    /// <summary>"forest_theme" -> "ForestTheme", "jump.wav" -> "Jump".</summary>
    public static string Pascal(string name)
    {
        var sb = new StringBuilder();
        var up = true;
        foreach (var c in Names.StripExtension(name))
        {
            if (!char.IsAsciiLetterOrDigit(c)) { up = true; continue; }
            sb.Append(up ? char.ToUpperInvariant(c) : c);
            up = false;
        }
        if (sb.Length == 0 || char.IsDigit(sb[0])) sb.Insert(0, '_');
        return sb.ToString();
    }

    static string Doc(string text) => "/// <summary>" + System.Security.SecurityElement.Escape(text) + "</summary>";

    // ---- C# ---------------------------------------------------------------------------------------------

    /// <summary>The generated C# API (compiled with the scripts and written for external IDEs).</summary>
    public static string CSharp(ScriptCompileContext ctx, IReadOnlyList<ScriptVarDef> vars)
    {
        var sb = new StringBuilder();
        sb.Append("// <auto-generated/>\n");
        sb.Append($"// AGB Studio project API for {ctx.ProjectName}. Regenerated on every build from the project settings.\n");
        sb.Append("#pragma warning disable\n");
        sb.Append("global using Fixed = global::GBA.@fixed;\n\n");
        sb.Append("namespace GBA\n{\n");

        // Game state
        sb.Append("    " + Doc("Game state from Project Settings · Save data. Save.Write stores it, Save.Read restores it.") + "\n");
        sb.Append("    [Cpp(\"agb_state\")]\n    public static class Game\n    {\n");
        for (var i = 0; i < ctx.SaveFields.Count; i++)
        {
            var f = ctx.SaveFields[i];
            var (cs, op) = SaveFieldType(f, ctx);
            if (cs == null) continue;
            sb.Append($"        {Doc($"Save field {f.Name} ({f.Type}).")}\n");
            sb.Append($"        [Cpp(\"agb_state.{BuildCpp.Ident(f.Name)}\")]{(op ? $" [ScriptOp(\"game:{i}\")]" : "")} public static {cs} {CsIdent(f.Name)};\n");
        }
        sb.Append("    }\n\n");

        NameConstants(sb, "Sounds", "Sound effect names for Sound.Play.", ctx.Sounds.Keys);
        NameConstants(sb, "Songs", "Music names for Music.Play.", ctx.Music.Keys);
        NameConstants(sb, "Scenes", "Scene names for Scene.Load.", ctx.Scenes.Keys);
        NameConstants(sb, "Tags", "Actor tags (compare with actor.tag).", ctx.Tags.Keys);
        NameConstants(sb, "Path", "Movement paths for Move(actor, path).", ctx.Paths.Select(p => p.Name));
        NameConstants(sb, "Speakers", "Dialogue speakers for Say(key, speaker).", ctx.Speakers.Keys);

        // Enums of typed script variables
        foreach (var e in ctx.Enums)
        {
            sb.Append($"    {Doc($"Values of the script variable type {e.Name}.")}\n");
            sb.Append($"    [Cpp(\"agbgen::{BuildCpp.Ident(e.Name)}\")]\n    public enum {CsIdent(e.Name)}\n    {{\n");
            foreach (var v in e.Values) sb.Append($"        {Doc(v)}\n        {CsIdent(v)},\n");
            sb.Append("    }\n\n");
        }

        // Typed script variables, grouped by class (Story, Flags, ...)
        foreach (var group in vars.GroupBy(v => v.Group).OrderBy(g => g.Key, StringComparer.Ordinal))
        {
            sb.Append($"    {Doc($"Script variables ({group.Key}) of the Event Script state store.")}\n");
            sb.Append($"    public static class {CsIdent(group.Key)}\n    {{\n");
            foreach (var v in group)
            {
                var id = "0x" + v.Id.ToString("X4", CultureInfo.InvariantCulture);
                string type, get, set, op;
                if (v.Type == "bool")
                {
                    type = "bool";
                    get = $"agb::script::flag({id})";
                    set = $"agb::script::setFlag({id}, {{value}})";
                    op = $"flag:{v.Id}";
                }
                else if (v.Type == "int")
                {
                    type = "int";
                    get = $"agb::script::var({id})";
                    set = $"agb::script::setVar({id}, {{value}})";
                    op = $"var:{v.Id}";
                }
                else
                {
                    type = CsIdent(v.Type);
                    get = $"static_cast<agbgen::{BuildCpp.Ident(v.Type)}>(agb::script::var({id}))";
                    set = $"agb::script::setVar({id}, static_cast<agb::s32>({{value}}))";
                    op = $"var:{v.Id}";
                }
                var space = v.Id >= 0x8000 ? "session" : v.Id >= 0x4000 ? "per-map" : "saved";
                sb.Append($"        {Doc($"{v.Group}.{v.Name} ({v.Type}, {space}).")}\n");
                sb.Append($"        [Cpp(\"{get}\", Set = \"{set}\")] [ScriptOp(\"{op}\")]\n");
                sb.Append($"        public static {type} {CsIdent(v.Name)} {{ get => default; set {{ }} }}\n");
            }
            sb.Append("    }\n\n");
        }

        // Database tables
        for (var ti = 0; ti < ctx.Tables.Count; ti++) Table(sb, ctx, ctx.Tables[ti], ti);
        Shop(sb, ctx);
        sb.Append("}\n");
        return sb.ToString();
    }

    static void NameConstants(StringBuilder sb, string cls, string doc, IEnumerable<string> names)
    {
        var list = names.Distinct().OrderBy(n => n, StringComparer.Ordinal).ToList();
        if (list.Count == 0) return;
        sb.Append($"    {Doc(doc)}\n    public static class {cls}\n    {{\n");
        var used = new HashSet<string>();
        foreach (var n in list)
        {
            var id = Pascal(n);
            if (!used.Add(id)) continue;
            sb.Append($"        {Doc(n)}\n        public const string {id} = {Scripting.Names.CsString(Scripting.Names.StripExtension(n))};\n");
        }
        sb.Append("    }\n\n");
    }

    static (string? Type, bool ScriptOp) SaveFieldType(SaveField f, ScriptCompileContext ctx)
    {
        var t = f.Type.Trim();
        if (t.StartsWith("bitset", StringComparison.Ordinal)) return ("Bitset", false);
        var open = t.IndexOf('[');
        if (open > 0)
        {
            if (t[..open].Trim() == "short") return ("ShortList", false);
            var table = ctx.Tables.FirstOrDefault(x => x.Name == t[..open].Trim());
            return (table != null ? DatabaseCodegen.IdEnum(table.Name) + "List" : null, false);
        }
        return t switch
        {
            "int" => ("int", true),
            "byte" => ("byte", true),
            "short" => ("short", true),
            "fixed" => ("@fixed", true),
            "bool" => ("bool", true),
            "fixed2" => ("fixed2", false),
            _ => ("int", true),
        };
    }

    static string Capital(string s) => s.Length == 0 ? s : char.ToUpperInvariant(s[0]) + s[1..];

    static void Table(StringBuilder sb, ScriptCompileContext ctx, TableFile t, int index)
    {
        var st = DatabaseCodegen.RowStruct(t.Name);
        var idEnum = DatabaseCodegen.IdEnum(t.Name);
        var ids = t.Rows.Select(r => r.GetValueOrDefault(t.KeyField) ?? "").ToList();
        sb.Append($"    {Doc($"Row ids of the {t.Name} table.")}\n");
        sb.Append($"    [Cpp(\"agb_db::{idEnum}\")]\n    public enum {idEnum} : ushort\n    {{\n");
        foreach (var id in ids) sb.Append($"        {Doc(id)}\n        {CsIdent(BuildCpp.Ident(id))},\n");
        sb.Append("    }\n\n");
        var fields = t.Fields.Where(f => f.Name != t.KeyField).ToList();
        foreach (var f in fields.Where(f => f.Type == "enum"))
        {
            var en = st + BuildCpp.Ident(Capital(f.Name));
            sb.Append($"    {Doc($"Values of {t.Name}.{f.Name}.")}\n    [Cpp(\"agb_db::{en}\")]\n    public enum {en} : byte\n    {{\n");
            foreach (var v in f.EnumValues) sb.Append($"        {Doc(v)}\n        {CsIdent(BuildCpp.Ident(v))},\n");
            sb.Append("    }\n\n");
        }
        sb.Append($"    {Doc($"A row of the {t.Name} table.")}\n    [Cpp(\"agb_db::{st}\")]\n    public struct {st}\n    {{\n");
        foreach (var f in fields)
        {
            var member = BuildCpp.Ident(f.Name);
            if (f.Type == "script")
            {
                // Script cells (Effect column) are code: Items.Get(ItemId.Potion).effect() runs the row's cell.
                sb.Append($"        {Doc($"Runs this row's {f.Name} cell (script); an empty cell does nothing.")}\n");
                sb.Append($"        [Cpp(\"agb_db::Run({{this.}}{member})\")] public void {CsIdent(f.Name)}() {{ }}\n");
                continue;
            }
            var (cs, cpp) = f.Type switch
            {
                "int" => ("int", (string?)null),
                "fixed" => ("@fixed", null),
                "bool" => ("bool", null),
                "text" => f.Localized ? ("int", null) : ("string", null),
                "enum" => (st + BuildCpp.Ident(Capital(f.Name)), null),
                "sound" => ("int", null),
                "reference" when ctx.Tables.Any(x => x.Name == f.Reference) =>
                    (DatabaseCodegen.IdEnum(f.Reference), $"static_cast<agb_db::{DatabaseCodegen.IdEnum(f.Reference)}>({{this.}}{member})"),
                _ => ((string?)null, (string?)null),
            };
            if (cs == null) continue;
            var doc = f.Type == "text" && f.Localized ? $"{f.Name} (string id of a localized text)." : $"{f.Name} ({f.Type}).";
            sb.Append($"        {Doc(doc)}\n");
            if (cpp != null) sb.Append($"        [Cpp(\"{cpp}\")] public {cs} {CsIdent(f.Name)} => default;\n");
            else sb.Append($"        [Cpp(\"{{this.}}{member}\")] public {cs} {CsIdent(f.Name)};\n");
        }
        sb.Append("    }\n\n");
        var cls = BuildCpp.Ident(t.Name);
        sb.Append($"    {Doc($"The {t.Name} table (data/{t.Name}.db), stored in ROM.")}\n    [Cpp(\"agb_db::{cls}\")]\n    public static class {cls}\n    {{\n");
        sb.Append($"        {Doc("The row with this id.")}\n        [Cpp(\"agb_db::{cls}::Get({{0}})\")] public static {st} Get({idEnum} id) => default;\n");
        sb.Append($"        {Doc("Number of rows.")}\n        [Cpp(\"agb_db::{cls}::Count()\")] public static int Count => 0;\n");
        sb.Append($"        {Doc("Gives items of this table to the player (Give item hook).")}\n");
        sb.Append($"        [Cpp(\"agb::script::natives::giveItem({index}, static_cast<agb::s32>({{0}}), {{1}})\")] [ScriptOp(\"native:GiveItem:{index}\")]\n");
        sb.Append($"        public static void Give({idEnum} id, int count = 1) {{ }}\n    }}\n\n");
        // Save fields holding ids of this table (Items[16]).
        sb.Append($"    {Doc($"A save field that holds {t.Name} ids.")}\n    public struct {idEnum}List\n    {{\n");
        sb.Append($"        {Doc("The id at a position.")}\n");
        sb.Append($"        [Cpp(\"static_cast<agb_db::{idEnum}>({{this}}[{{0}}])\", Set = \"{{this}}[{{0}}] = static_cast<unsigned short>({{value}})\")]\n");
        sb.Append($"        public {idEnum} this[int index] {{ get => default; set {{ }} }}\n");
        sb.Append($"        {Doc("Number of positions.")}\n        [Cpp(\"agb_countof({{this}})\")] public int Length => 0;\n    }}\n\n");
    }

    static bool HasShop(ScriptCompileContext ctx, TableFile t) =>
        t.Fields.Any(f => f.Name == "price" && f.Type == "int") &&
        ctx.SaveFields.Any(f => f.Name == ctx.ShopCurrencyField && f.Type.Trim() is "int" or "short");

    static void Shop(StringBuilder sb, ScriptCompileContext ctx)
    {
        var tables = ctx.Tables.Where(t => HasShop(ctx, t)).ToList();
        if (tables.Count == 0) return;
        sb.Append($"    {Doc($"Buying from database tables with a price field; spends Game.{ctx.ShopCurrencyField}.")}\n");
        sb.Append("    public static class Shop\n    {\n");
        foreach (var t in tables)
        {
            var idEnum = DatabaseCodegen.IdEnum(t.Name);
            sb.Append($"        {Doc($"Spends the price of the {DatabaseCodegen.Singular(t.Name)} and gives it; false when there is not enough money.")}\n");
            sb.Append($"        [Cpp(\"agbgen::shopBuy_{BuildCpp.Ident(t.Name)}({{0}})\")] public static bool Buy({idEnum} id) => false;\n");
        }
        sb.Append("    }\n\n");
    }

