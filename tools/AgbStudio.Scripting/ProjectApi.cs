    /// <summary>
    /// Files the game build normally writes (agb_game.hpp, soundbank.hpp, agb_db.hpp and table sources), in the
    /// same format, for compiling scripts without the build (tests, tools). Returns (file name, text).
    /// </summary>
    public static List<(string File, string Text)> StandInHeaders(ScriptCompileContext ctx)
    {
        var files = new List<(string, string)>();
        var h = new StringBuilder();
        h.Append("// Generated by AGB Studio (scripting stand-in for the game build). Do not edit.\n#pragma once\n#include \"agb/api.hpp\"\n\n");
        h.Append("#include \"agb/script.hpp\"\n");
        h.Append("struct GameState {\n    agb::SaveHeader header;\n");
        foreach (var f in ctx.SaveFields) h.Append($"    {FieldDecl(f)};\n");
        h.Append("    agb::script::PersistentStore scriptStore;  // saved script flags and variables\n");
        h.Append("};\nextern GameState agb_state;\n\nnamespace agb_scene {\n");
        foreach (var (name, i) in ctx.Scenes.OrderBy(x => x.Value)) h.Append($"constexpr unsigned short {BuildCpp.Ident(name)} = {i};\n");
        h.Append("}\nnamespace agb_tag {\n");
        foreach (var (name, i) in ctx.Tags.OrderBy(x => x.Value)) h.Append($"constexpr unsigned short {BuildCpp.Ident(name)} = {i};\n");
        h.Append("}\nnamespace agb_text {\n");
        foreach (var (name, i) in ctx.Strings.OrderBy(x => x.Value)) h.Append($"constexpr unsigned short {BuildCpp.Ident(name)} = {i};\n");
        h.Append("}\n");
        files.Add(("agb_game.hpp", h.ToString()));
        files.Add(("agb_game_state.cpp", "// Generated by AGB Studio (scripting stand-in). Do not edit.\n#include \"agb_game.hpp\"\nGameState agb_state;\n"));
        if (ctx.Sounds.Count + ctx.Music.Count > 0)
        {
            var s = new StringBuilder("// Generated by AGB Studio (scripting stand-in). Do not edit.\n#pragma once\nnamespace agb_sound {\n");
            foreach (var (name, i) in ctx.Music.OrderBy(x => x.Value)) s.Append($"constexpr unsigned short MOD_{BuildCpp.Ident(Scripting.Names.StripExtension(name)).ToUpperInvariant()} = {i};\n");
            foreach (var (name, i) in ctx.Sounds.OrderBy(x => x.Value)) s.Append($"constexpr unsigned short SFX_{BuildCpp.Ident(Scripting.Names.StripExtension(name)).ToUpperInvariant()} = {i};\n");
            s.Append("}  // namespace agb_sound\n");
            files.Add(("soundbank.hpp", s.ToString()));
        }
        if (ctx.Tables.Count > 0)
        {
            var diags = new List<AgbStudio.Build.Pipeline.Diagnostic>();
            var o = DatabaseCodegen.Generate(ctx.Tables, k => ctx.Strings.TryGetValue(k, out var v) ? v : -1,
                n => ScriptsSound(ctx, n), _ => false, diags, "", scriptCells: true);
            // DatabaseCodegen declares script fields as "void (*)() name;", which is not valid C++ (reported to the build
            // owner); the stand-in writes the valid "void (*name)();".
            var header = System.Text.RegularExpressions.Regex.Replace(o.Header, @"void \(\*\)\(\) (\w+);", "void (*$1)();");
            files.Add(("agb_db.hpp", header));
            foreach (var (file, text) in o.Sources) files.Add((file, text));
        }
        return files;
    }

    static int ScriptsSound(ScriptCompileContext ctx, string name)
    {
        var key = Translation.ScriptModel.FindKey(ctx.Sounds, name);
        return key != null ? ctx.Sounds[key] : -1;
    }

    /// <summary>GameState member declaration, as the game build writes it.</summary>
    public static string FieldDecl(SaveField f)
    {
        var t = f.Type.Trim();
        var name = BuildCpp.Ident(f.Name);
        if (t.StartsWith("bitset", StringComparison.Ordinal)) return $"unsigned char {name}[{(int.Parse(t[6..].Trim(), CultureInfo.InvariantCulture) + 7) / 8}]";
        var open = t.IndexOf('[');
        if (open > 0) return $"unsigned short {name}[{t[(open + 1)..t.IndexOf(']')]}]";
        return t switch
        {
            "bool" => $"bool {name}",
            "byte" => $"unsigned char {name}",
            "short" => $"short {name}",
            "fixed" => $"agb::fixed {name}",
            "fixed2" => $"agb::fixed2 {name}",
            _ => $"int {name}",
        };
    }
