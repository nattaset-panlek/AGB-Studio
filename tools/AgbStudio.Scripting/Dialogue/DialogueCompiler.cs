using System.Globalization;
using System.Text;
using System.Text.Json;
using System.Text.RegularExpressions;
using BuildCpp = AgbStudio.Build.Pipeline.Cpp;

namespace AgbStudio.Scripting.Dialogue;

/// <summary>
/// Turns a dialogue file into C#: one <c>[Cutscene] static async Task</c> per conversation (script name
/// <c>&lt;file&gt;.&lt;conversation&gt;</c>), which the bytecode compiler turns into Event Script bytecode. Lines
/// become Say, choices Choice + switch, "Show if" an if, "Then set" assignments, goto targets labels. <c>#line</c>
/// directives point errors at the .dlg file.
/// </summary>
public static partial class DialogueCompiler
{
    [GeneratedRegex(@"\bFlags\.(\w+)")]
    private static partial Regex FlagRef();

    public const string Namespace = "AgbGenerated.Dialogue";

    /// <summary>C# class name of a dialogue file.</summary>
    public static string ClassName(DialogueFile f, string path) =>
        Names.Identifier(f.Name.Length > 0 ? f.Name : Path.GetFileNameWithoutExtension(path));

    /// <summary>
    /// Generates the C# for a dialogue. Flags used by "Set flag" or conditions that the project does not declare are
    /// added to <paramref name="vars"/> as persistent flags (and listed in <paramref name="autoFlags"/>).
    /// </summary>
    public static string ToCSharp(DialogueFile f, string path, ScriptCompileContext ctx, List<ScriptVarDef> vars,
        Dictionary<string, int> autoFlags, out List<ScriptDiagnostic> diagnostics)
    {
        diagnostics = new List<ScriptDiagnostic>();
        DeclareFlags(f, vars, autoFlags);
        var file = path.Replace('\\', '/');
        var cls = ClassName(f, path);
        var sb = new StringBuilder();
        sb.Append("// <auto-generated/>\n#pragma warning disable\nusing GBA;\nusing System.Threading.Tasks;\n\n");
        sb.Append($"namespace {Namespace}\n{{\n    public sealed class {cls} : ScriptBase\n    {{\n");
        var speakers = f.Speakers.ToDictionary(s => s.Name, StringComparer.Ordinal);
        var methods = new HashSet<string>();
        for (var ci = 0; ci < f.Conversations.Count; ci++)
        {
            var c = f.Conversations[ci];
            var method = Names.Identifier(c.Id.Length > 0 ? c.Id : "conversation" + ci);
            if (!methods.Add(method))
            {
                diagnostics.Add(new ScriptDiagnostic("AGB0400", ScriptSeverity.Error, $"Two conversations are named '{c.Id}'.", path, Line(f, $"/conversations/{ci}"), 1));
                continue;
            }
            var ids = c.Lines.Select((l, i) => l.Id ?? $"line{i}").ToList();
            var labels = new HashSet<string>(c.Lines.Where(l => l.Id != null).Select(l => l.Id!), StringComparer.Ordinal);
            sb.Append($"#line {Line(f, $"/conversations/{ci}")} \"{file}\"\n");
            sb.Append($"        [Cutscene] public static async Task {method}()\n        {{\n");
            for (var li = 0; li < c.Lines.Count; li++)
            {
                var l = c.Lines[li];
                var at = $"/conversations/{ci}/lines/{li}";
                sb.Append($"#line {Line(f, at)} \"{file}\"\n");
                // Label and statement share the line that #line maps to the dialogue line.
                sb.Append($"            {Label(ids[li])}: ;");
                var body = new StringBuilder();
                if (l.Command != null) Command(body, l, f, at, path, diagnostics);
                else Say(body, f, c, l, speakers, labels, at, path, file, diagnostics, ci, li);
                if (l.Next != null)
                {
                    if (!labels.Contains(l.Next)) diagnostics.Add(new ScriptDiagnostic("AGB0401", ScriptSeverity.Error, $"Line '{l.Next}' does not exist in conversation '{c.Id}' (Next).", path, Line(f, at), 1));
                    else body.Append($"goto {Label(l.Next)};");
                }
                var text = body.ToString().Trim();
                if (l.ShowIf is { Length: > 0 } cond) sb.Append($" if ({cond}) {{ {text} }}\n");
                else sb.Append(text.Length > 0 ? $" {text}\n" : "\n");
            }
            sb.Append("#line default\n        }\n\n");
        }
        sb.Append("    }\n}\n");
        return sb.ToString();
    }

    static string Label(string id) => "line_" + Names.Identifier(id);

    static int Line(DialogueFile f, string pointer) => f.LineOf.TryGetValue(pointer, out var l) ? l : 1;

    static string ThenSet(JsonElement? e)
    {
        if (e == null) return "";
        var v = e.Value;
        var items = v.ValueKind switch
        {
            JsonValueKind.String => [v.GetString() ?? ""],
            JsonValueKind.Array => v.EnumerateArray().Select(x => x.GetString() ?? "").ToList(),
            _ => new List<string>(),
        };
        return string.Concat(items.Where(s => s.Trim().Length > 0).Select(s => s.Trim().TrimEnd(';') + "; "));
    }

    static string Str(string? s) => s == null ? "null" : Names.CsString(s);

    static void Say(StringBuilder sb, DialogueFile f, Conversation c, DialogueLine l, Dictionary<string, DialogueSpeaker> speakers,
        HashSet<string> labels, string at, string path, string file, List<ScriptDiagnostic> diags, int ci, int li)
    {
        var key = l.Key ?? $"{(f.Name.Length > 0 ? f.Name : Path.GetFileNameWithoutExtension(path))}.{c.Id}.{l.Id ?? "line" + li}";
        speakers.TryGetValue(l.Speaker ?? "", out var sp);
        var portrait = l.Portrait ?? sp?.Portrait;
        var speed = l.Speed ?? (sp != null && sp.TextSpeed >= 0 ? sp.TextSpeed : f.TextSpeed);
        var blip = l.Blip ?? sp?.Blip ?? f.Blip;
        sb.Append($"await Say({Str(key)}, {Str(l.Speaker)}, {Str(portrait)}, {speed.ToString(CultureInfo.InvariantCulture)}, {Str(blip)}); ");
        sb.Append(ThenSet(l.ThenSet));
        if (l.Choices is not { Count: > 0 }) return;
        var options = l.Choices.Select((ch, i) =>
        {
            var k = Str(ch.Key ?? $"{key}.choice{i}");
            return ch.ShowIf is { Length: > 0 } cond ? $"({cond}) ? {k} : null" : k;
        });
        sb.Append($"switch (await Choice({string.Join(", ", options)})) {{ ");
        for (var i = 0; i < l.Choices.Count; i++)
        {
            var ch = l.Choices[i];
            sb.Append($"case {i}: {ThenSet(ch.ThenSet)}");
            if (ch.Goto != null)
            {
                if (!labels.Contains(ch.Goto))
                    diags.Add(new ScriptDiagnostic("AGB0401", ScriptSeverity.Error, $"Choice {i + 1} goes to line '{ch.Goto}', which does not exist in conversation '{c.Id}'.", path, Line(f, $"{at}/choices/{i}"), 1));
                else sb.Append($"goto {Label(ch.Goto)}; ");
            }
            else if (ch.Scene != null) sb.Append($"Scene.Load({Str(ch.Scene)}); return; ");
            else if (ch.End) sb.Append("return; ");
            else sb.Append("break; ");
        }
        sb.Append("} ");
        _ = file;
        _ = ci;
    }

    static void Command(StringBuilder sb, DialogueLine l, DialogueFile f, string at, string path, List<ScriptDiagnostic> diags)
    {
        switch (l.Command)
        {
            case "goToScene":
                sb.Append($"Scene.Load({Str(l.Scene)}); return;");
                break;
            case "setFlag":
                sb.Append($"Flags.{ProjectApi.CsIdent(l.Flag ?? "")} = {((l.Value ?? true) ? "true" : "false")};");
                break;
            case "giveItem":
                {
                    var table = l.Table ?? "Items";
                    sb.Append($"{BuildCpp.Ident(table)}.Give({AgbStudio.Build.Data.DatabaseCodegen.IdEnum(table)}.{ProjectApi.CsIdent(BuildCpp.Ident(l.Item ?? ""))}, {l.Count ?? 1});");
                    break;
                }
            case "playSound":
                sb.Append(l.Volume is { } v ? $"Sound.Play({Str(l.Sound)}, {v.ToString("0.0###", CultureInfo.InvariantCulture)});" : $"Sound.Play({Str(l.Sound)});");
                break;
            case "wait":
                {
                    var frames = l.Frames ?? (int)Math.Round((l.Seconds ?? 0.5) * 60);
                    sb.Append($"await Wait({frames});");
                    break;
                }
            case "shakeCamera":
                sb.Append($"Camera.Shake({l.Amplitude ?? 2}, {l.Frames ?? 20});");
                break;
            case "end":
                sb.Append("return;");
                break;
            default:
                diags.Add(new ScriptDiagnostic("AGB0402", ScriptSeverity.Error,
                    $"Unknown dialogue command '{l.Command}'. Commands: goToScene, setFlag, giveItem, playSound, wait, shakeCamera, end.", path, Line(f, at), 1));
                break;
        }
    }

    static void DeclareFlags(DialogueFile f, List<ScriptVarDef> vars, Dictionary<string, int> autoFlags)
    {
        var names = new SortedSet<string>(StringComparer.Ordinal);
        void Scan(string? text)
        {
            if (text == null) return;
            foreach (Match m in FlagRef().Matches(text)) names.Add(m.Groups[1].Value);
        }
        foreach (var c in f.Conversations)
            foreach (var l in c.Lines)
            {
                if (l.Command == "setFlag" && l.Flag != null) names.Add(l.Flag);
                Scan(l.ShowIf);
                Scan(l.ThenSet?.ToString());
                foreach (var ch in l.Choices ?? [])
                {
                    Scan(ch.ShowIf);
                    Scan(ch.ThenSet?.ToString());
                }
            }
        foreach (var n in names)
        {
            if (vars.Any(v => v.Group == "Flags" && v.Name == n)) continue;
            var used = vars.Where(v => v.Type == "bool" && v.Id < 0x4000).Select(v => v.Id).ToHashSet();
            var id = 0;
            while (used.Contains(id)) id++;
            vars.Add(new ScriptVarDef { Group = "Flags", Name = n, Type = "bool", Id = id });
            autoFlags[n] = id;
        }
    }
}
