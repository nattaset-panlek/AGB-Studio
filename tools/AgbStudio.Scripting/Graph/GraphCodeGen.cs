using System.Globalization;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace AgbStudio.Scripting.Graph;

/// <summary>Logic Graph -> C# (D-11: always). The output is a Behaviour class in the style of the Figma "Generated C#" panel.</summary>
public static class GraphCodeGen
{
    public const string HeaderPrefix = "// Generated by AGB Studio Logic Graph from ";

    static readonly string[] s_events = ["OnStart", "OnUpdate", "OnLateUpdate", "OnTouch", "OnDestroy"];
    static readonly HashSet<string> s_physics = ["IsOnGround", "VelocityX", "VelocityY", "SetVelocityX", "SetVelocityY", "Jump", "SetVelocity", "AddForce", "GetVelocity"];

    /// <summary>True for C# files written by the Logic Graph (read-only in the Script Editor).</summary>
    public static bool IsGenerated(string code) => code.TrimStart('﻿').StartsWith(HeaderPrefix, StringComparison.Ordinal);

    public static string Generate(LogicGraph g, string fileName) => Generate(g, fileName, out _);

    /// <summary>Generates C#; <paramref name="order"/> lists node ids in the order the code visits them.</summary>
    public static string Generate(LogicGraph g, string fileName, out List<string> order)
    {
        var gen = new Gen(g);
        var cls = g.Class.Length > 0 ? g.Class : Names.Identifier(fileName);
        var sb = new StringBuilder();
        sb.Append(HeaderPrefix).Append(fileName).Append(".graph. Edit the graph; this file is rewritten when it changes.\n");
        sb.Append("using GBA;\n\n");
        sb.Append($"public class {cls} : Behaviour\n{{\n");
        var usesBody = g.Nodes.Any(n => s_physics.Contains(n.Type));
        var members = new List<string>();
        if (usesBody) members.Add("    PlatformerBody body;\n");
        var startNodes = g.Nodes.Where(n => n.Type == "OnStart").ToList();
        if (usesBody && startNodes.Count == 0) members.Add("    void Start() => body = Get<PlatformerBody>();\n");
        // On Button: one method per button, called from Update when the button is pressed.
        var buttons = g.Nodes.Where(n => n.Type == "OnButton").Select(n => gen.Prop(n, "button")).Distinct().ToList();
        foreach (var ev in s_events)
        {
            var nodes = g.Nodes.Where(n => n.Type == ev).ToList();
            if (nodes.Count == 0 && !(ev == "OnUpdate" && buttons.Count > 0)) continue;
            var m = new StringBuilder();
            var sig = ev switch
            {
                "OnStart" => "void Start()",
                "OnUpdate" => "void Update()",
                "OnLateUpdate" => "void LateUpdate()",
                "OnTouch" => "void OnTouch(Actor other)",
                _ => "void OnDestroy()",
            };
            m.Append("    ").Append(sig).Append("\n    {\n");
            if (ev == "OnStart" && usesBody) m.Append("        body = Get<PlatformerBody>();\n");
            foreach (var n in nodes)
            {
                gen.Visit(n.Id);
                // The Tag field: a guard, so the code differs from a Compare Tag node after the event.
                if (ev == "OnTouch" && gen.Prop(n, "tag") is { Length: > 0 } tag) m.Append($"        if (other.tag != {Names.CsString(tag)}) return;\n");
                gen.Chain(m, n.Id, "out", 2);
            }
            if (ev == "OnUpdate")
                foreach (var b in buttons) m.Append($"        if (Input.Pressed(Key.{b})) OnButton{b}();\n");
            m.Append("    }\n");
            members.Add(m.ToString());
        }
        foreach (var b in buttons)
        {
            var m = new StringBuilder($"    void OnButton{b}()\n    {{\n");
            foreach (var n in g.Nodes.Where(n => n.Type == "OnButton" && gen.Prop(n, "button") == b))
            {
                gen.Visit(n.Id);
                gen.Chain(m, n.Id, "out", 2);
            }
            m.Append("    }\n");
            members.Add(m.ToString());
        }
        sb.Append(string.Join("\n", members));
        sb.Append("}\n");
        order = gen.Order;
        return sb.ToString();
    }

    sealed class Gen(LogicGraph g)
    {
        public List<string> Order { get; } = new();

        public void Visit(string id)
        {
            if (!Order.Contains(id)) Order.Add(id);
        }

        public string Prop(GraphNode n, string prop) => P(n, prop);

        // The PlatformerBody a physics node acts on: the graph's own, or the one of the actor wired to Target.
        string Body(GraphNode n)
        {
            var link = g.Into(n.Id, "target");
            return link == null ? "body" : Input(n, "target", null, 16) + ".Get<PlatformerBody>()";
        }

        string P(GraphNode n, string prop)
        {
            if (n.Props.TryGetValue(prop, out var v)) return v;
            return NodeCatalog.Find(n.Type)?.Props.FirstOrDefault(p => p.Name == prop)?.Default ?? "";
        }

        static string Str(string s) => Names.CsString(s);

        public void Chain(StringBuilder sb, string node, string pin, int indent)
        {
            foreach (var link in g.OutOf(node, pin))
            {
                var next = g.Node(link.ToNode);
                if (next != null) Statement(sb, next, indent);
            }
        }

        void Line(StringBuilder sb, int indent, string text) => sb.Append(new string(' ', indent * 4)).Append(text).Append('\n');

        void Statement(StringBuilder sb, GraphNode n, int indent)
        {
            Visit(n.Id);
            switch (n.Type)
            {
                case "Branch":
                    {
                        var cond = Input(n, "condition", null, 0);
                        Line(sb, indent, $"if ({cond})");
                        Line(sb, indent, "{");
                        Chain(sb, n.Id, "true", indent + 1);
                        Line(sb, indent, "}");
                        if (g.OutOf(n.Id, "false").Any())
                        {
                            Line(sb, indent, "else");
                            Line(sb, indent, "{");
                            Chain(sb, n.Id, "false", indent + 1);
                            Line(sb, indent, "}");
                        }
                        return;
                    }
                case "CompareTag":
                    {
                        var actor = Input(n, "actor", null, 16);
                        Line(sb, indent, $"if ({actor}.tag == {Str(P(n, "tag"))})");
                        Line(sb, indent, "{");
                        Chain(sb, n.Id, "match", indent + 1);
                        Line(sb, indent, "}");
                        return;
                    }
            }
            var text = n.Type switch
            {
                "SetVelocityX" => $"body.vx = {Input(n, "value", "value", 3)};",
                "SetVelocityY" => P(n, "mode") switch
                {
                    "Add" => $"{Body(n)}.vy += {Input(n, "value", "value", 3)};",
                    "Clamp" => $"{Body(n)}.vy = fixed.Min({Body(n)}.vy, {Input(n, "value", "value", 0)});",
                    _ => $"{Body(n)}.vy = {Input(n, "value", "value", 3)};",
                },
                "SetVelocity" => $"{Body(n)}.SetVelocity({Input(n, "x", "x", 0)}, {Input(n, "y", "y", 0)});",
                "AddForce" => $"{Body(n)}.AddForce({Input(n, "x", "x", 0)}, {Input(n, "y", "y", 0)});",
                "Jump" => "body.Jump();",
                "Destroy" => $"{Input(n, "actor", null, 16)}.Destroy();",
                "PlaySound" => P(n, "volume") is var vol && (vol.Length == 0 || IsOne(vol))
                    ? $"Sound.Play({Str(Names.StripExtension(P(n, "sound")))});"
                    : $"Sound.Play({Str(Names.StripExtension(P(n, "sound")))}, {vol});",
                "PlayMusic" => $"Music.Play({Str(Names.StripExtension(P(n, "music")))});",
                "StopMusic" => "Music.Stop();",
                "SetVariable" => $"Game.{P(n, "variable")} = {Input(n, "value", "value", 3)};",
                "AddToVariable" => $"Game.{P(n, "variable")} += {Input(n, "amount", "amount", 3)};",
                "SaveGame" => $"Save.Write({P(n, "slot")});",
                "Checkpoint" => "Save.Checkpoint();",
                "ShowText" => $"Text.Show({Str(P(n, "key"))});",
                "DebugLog" => $"Debug.Log({Str(P(n, "text"))});",
                "LoadScene" => $"Scene.Load({Str(P(n, "scene"))});",
                "ShakeCamera" => $"Camera.Shake({P(n, "amplitude")}, {P(n, "frames")});",
                "CameraFollow" => $"Camera.Follow({Input(n, "target", null, 0)});",
                "LoadGame" => $"Save.Read({P(n, "slot")});",
                "SetTile" => $"Scene.SetTile({P(n, "layer")}, {P(n, "x")}, {P(n, "y")}, {P(n, "tile")});",
                _ => $"// {n.Type} is not an action",
            };
            Line(sb, indent, text);
            Chain(sb, n.Id, "out", indent);
        }

        static bool IsOne(string s) => double.TryParse(s, NumberStyles.Float, CultureInfo.InvariantCulture, out var d) && d == 1;

        /// <summary>The expression feeding an input pin (or the node's prop when the pin is not connected).</summary>
        string Input(GraphNode n, string pin, string? prop, int minPrec)
        {
            var link = g.Into(n.Id, pin);
            if (link != null && g.Node(link.FromNode) is { } src)
            {
                if (src.Type.StartsWith("On", StringComparison.Ordinal) && link.FromPin == "other") return "other";
                var (text, prec) = Value(src);
                return prec >= minPrec ? text : "(" + text + ")";
            }
            var pinKind = NodeCatalog.Find(n.Type)?.Pin(pin)?.Kind;
            if (pinKind == PinKind.Actor) return "actor";
            var v = prop != null ? P(n, prop) : "";
            if (v.Length == 0) v = pinKind == PinKind.Bool ? "false" : "0";
            return v.StartsWith('-') && minPrec > 15 ? "(" + v + ")" : v;
        }

        (string Text, int Prec) Value(GraphNode n)
        {
            Visit(n.Id);
            return n.Type switch
            {
                "ButtonPressed" => ($"Input.Pressed(Key.{P(n, "button")})", 16),
                "ButtonHeld" => ($"Input.Held(Key.{P(n, "button")})", 16),
                "ButtonReleased" => ($"Input.Released(Key.{P(n, "button")})", 16),
                "AxisX" => ("Input.AxisX", 16),
                "AxisY" => ("Input.AxisY", 16),
                "AnyKey" => ("Input.AnyKey", 16),
                "IsOnGround" => ($"{Body(n)}.OnGround", 16),
                "GetVelocity" => ($"{Body(n)}.Velocity", 16),
                "VectorFromVelocity" => ($"new fixed2({Input(n, "vx", "vx", 0)}, {Input(n, "vy", "vy", 0)})", 16),
                "VelocityX" => ("body.vx", 16),
                "VelocityY" => ("body.vy", 16),
                "And" => ($"{Input(n, "a", null, 6)} && {Input(n, "b", null, 7)}", 6),
                "Or" => ($"{Input(n, "a", null, 5)} || {Input(n, "b", null, 6)}", 5),
                "Not" => ($"!{Input(n, "a", null, 15)}", 15),
                "Add" => ($"{Input(n, "a", "a", 13)} + {Input(n, "b", "b", 14)}", 13),
                "Subtract" => ($"{Input(n, "a", "a", 13)} - {Input(n, "b", "b", 14)}", 13),
                "Multiply" => ($"{Input(n, "a", "a", 14)} * {Input(n, "b", "b", 15)}", 14),
                "Compare" => P(n, "op") is "==" or "!="
                    ? ($"{Input(n, "a", "a", 10)} {P(n, "op")} {Input(n, "b", "b", 11)}", 10)
                    : ($"{Input(n, "a", "a", 11)} {P(n, "op")} {Input(n, "b", "b", 12)}", 11),
                "Self" => ("actor", 16),
                "GetVariable" => ($"Game.{P(n, "variable")}", 16),
                "RandomRange" => ($"Random.Range({P(n, "lo")}, {P(n, "hi")})", 16),
                "SaveExists" => ($"Save.Exists({P(n, "slot")})", 16),
                _ => ("false", 16),
            };
        }
    }
}

/// <summary>
/// C# -> Logic Graph for files the graph generated (D-11). Rebuilds the nodes and links from the generated shape; when
/// the previous graph is given, node ids, positions and the typed text of props ("jump.wav", "-3.50") are kept.
/// </summary>
public static class GraphFromCode
{
    public static LogicGraph Parse(string code, LogicGraph? previous = null)
    {
        if (!GraphCodeGen.IsGenerated(code))
            throw new FormatException("Only C# files generated by the Logic Graph can be turned back into a graph (D-11).");
        var root = CSharpSyntaxTree.ParseText(FixedKeyword.Rewrite(code)).GetCompilationUnitRoot();  // D-22: fixed.Min parses as Fixed.Min
        var cls = root.DescendantNodes().OfType<ClassDeclarationSyntax>().FirstOrDefault()
            ?? throw new FormatException("The file has no class.");
        var b = new Builder();
        b.G.Class = cls.Identifier.ValueText;
        foreach (var m in cls.Members.OfType<MethodDeclarationSyntax>())
        {
            if (m.Identifier.ValueText.StartsWith("OnButton", StringComparison.Ordinal))
            {
                var bn = b.Add("OnButton", ("button", m.Identifier.ValueText["OnButton".Length..]));
                b.Chain(m.Body?.Statements.ToList() ?? [], bn.Id, "out");
                continue;
            }
            var ev = m.Identifier.ValueText switch
            {
                "Start" => "OnStart",
                "Update" => "OnUpdate",
                "LateUpdate" => "OnLateUpdate",
                "OnTouch" => "OnTouch",
                "OnDestroy" => "OnDestroy",
                _ => throw new FormatException($"Method {m.Identifier.ValueText} is not a graph event."),
            };
            var statements = m.Body?.Statements.ToList() ?? (m.ExpressionBody != null ? [SyntaxFactory.ExpressionStatement(m.ExpressionBody.Expression)] : []);
            // The body field initialization belongs to the generated Start, not to a node.
            statements = statements.Where(s => s.ToString().Replace(" ", "") != "body=Get<PlatformerBody>();").ToList();
            // On Button dispatch lines belong to the On Button methods.
            statements = statements.Where(s => !(s is IfStatementSyntax { Statement: ExpressionStatementSyntax { Expression: InvocationExpressionSyntax call } }
                && call.Expression.ToString().StartsWith("OnButton", StringComparison.Ordinal))).ToList();
            if ((ev == "OnStart" || ev == "OnUpdate") && statements.Count == 0) continue;
            var node = b.Add(ev);
            // On Touch's Tag field: "if (other.tag != "Coin") return;" first.
            if (ev == "OnTouch" && statements.Count > 0 && statements[0] is IfStatementSyntax { Else: null, Statement: ReturnStatementSyntax, Condition: BinaryExpressionSyntax { RawKind: (int)SyntaxKind.NotEqualsExpression } teq } &&
                teq.Left.ToString() == "other.tag" && teq.Right is LiteralExpressionSyntax tlit)
            {
                node.Props["tag"] = tlit.Token.ValueText;
                statements = statements.Skip(1).ToList();
            }
            b.Chain(statements, node.Id, "out");
        }
        Layout(b.G);
        if (previous != null) Merge(b.G, previous, b.Order);
        return b.G;
    }

    sealed class Builder
    {
        public LogicGraph G { get; } = new();
        public List<string> Order { get; } = new();

        public GraphNode Add(string type, params (string, string)[] props)
        {
            var n = new GraphNode { Id = "n" + (G.Nodes.Count + 1), Type = type };
            foreach (var (k, v) in props) n.Props[k] = v;
            G.Nodes.Add(n);
            Order.Add(n.Id);
            return n;
        }

        void Link(string from, string fromPin, string to, string toPin) => G.Links.Add(new GraphLink(from + "." + fromPin, to + "." + toPin));

        public void Chain(List<StatementSyntax> statements, string from, string pin)
        {
            var (prevNode, prevPin) = (from, pin);
            for (var i = 0; i < statements.Count; i++)
            {
                var s = statements[i];
                if (s is IfStatementSyntax ifs)
                {
                    if (i != statements.Count - 1) throw new FormatException("Statements after an if are not part of a generated graph.");
                    if (ifs.Else == null && ifs.Condition is BinaryExpressionSyntax { RawKind: (int)SyntaxKind.EqualsExpression } eq &&
                        eq.Left is MemberAccessExpressionSyntax { Name.Identifier.ValueText: "tag" } tag && eq.Right is LiteralExpressionSyntax lit)
                    {
                        var ct = Add("CompareTag", ("tag", lit.Token.ValueText));
                        Link(prevNode, prevPin, ct.Id, "in");
                        ActorInput(tag.Expression, ct.Id, "actor");
                        Chain(Block(ifs.Statement), ct.Id, "match");
                        return;
                    }
                    var br = Add("Branch");
                    Link(prevNode, prevPin, br.Id, "in");
                    ValueInput(ifs.Condition, br.Id, "condition", null);
                    Chain(Block(ifs.Statement), br.Id, "true");
                    if (ifs.Else != null) Chain(Block(ifs.Else.Statement), br.Id, "false");
                    return;
                }
                if (s is not ExpressionStatementSyntax { Expression: var e }) throw new FormatException($"'{s}' is not a graph statement.");
                var node = Action(e);
                Link(prevNode, prevPin, node.Id, "in");
                (prevNode, prevPin) = (node.Id, "out");
            }
        }

        static List<StatementSyntax> Block(StatementSyntax s) => s is BlockSyntax b ? b.Statements.ToList() : [s];

        GraphNode Action(ExpressionSyntax e)
        {
            switch (e)
            {
                case AssignmentExpressionSyntax a when a.Left.ToString() == "body.vx" && a.IsKind(SyntaxKind.SimpleAssignmentExpression):
                    return WithValue("SetVelocityX", a.Right, "value");
                case AssignmentExpressionSyntax a when Vy(a.Left) is { } vyBody:
                    {
                        // body.vy = v (Set), body.vy += v (Add), body.vy = fixed.Min(body.vy, v) (Clamp); "x.Get<PlatformerBody>()" wires Target.
                        if (a.IsKind(SyntaxKind.SimpleAssignmentExpression) && a.Right is InvocationExpressionSyntax { Expression: var mn } min &&
                            mn.ToString() is "fixed.Min" or "Fixed.Min" && min.ArgumentList.Arguments.Count == 2)
                            return Target(WithValue("SetVelocityY", min.ArgumentList.Arguments[1].Expression, "value", ("mode", "Clamp")), vyBody);
                        var mode = a.IsKind(SyntaxKind.AddAssignmentExpression) ? "Add" : "Set";
                        var n = WithValue("SetVelocityY", a.Right, "value");
                        if (mode == "Add") n.Props["mode"] = "Add";
                        return Target(n, vyBody);
                    }
                case AssignmentExpressionSyntax a when a.Left is MemberAccessExpressionSyntax { Expression: IdentifierNameSyntax { Identifier.ValueText: "Game" } } ma:
                    return a.IsKind(SyntaxKind.AddAssignmentExpression)
                        ? WithValue("AddToVariable", a.Right, "amount", ("variable", ma.Name.Identifier.ValueText))
                        : WithValue("SetVariable", a.Right, "value", ("variable", ma.Name.Identifier.ValueText));
                case InvocationExpressionSyntax inv:
                    {
                        var target = inv.Expression.ToString();
                        var args = inv.ArgumentList.Arguments.Select(x => x.Expression).ToList();
                        string Lit(int i) => i < args.Count ? args[i] is LiteralExpressionSyntax l && l.IsKind(SyntaxKind.StringLiteralExpression) ? l.Token.ValueText : args[i].ToString() : "";
                        switch (target)
                        {
                            case "body.Jump": return Add("Jump");
                            case "Sound.Play": return args.Count > 1 ? Add("PlaySound", ("sound", Lit(0)), ("volume", Lit(1))) : Add("PlaySound", ("sound", Lit(0)));
                            case "Music.Play": return Add("PlayMusic", ("music", Lit(0)));
                            case "Music.Stop": return Add("StopMusic");
                            case "Save.Write": return Add("SaveGame", ("slot", Lit(0)));
                            case "Save.Checkpoint": return Add("Checkpoint");
                            case "Text.Show": return Add("ShowText", ("key", Lit(0)));
                            case "Debug.Log": return Add("DebugLog", ("text", Lit(0)));
                            case "Scene.Load": return Add("LoadScene", ("scene", Lit(0)));
                            case "Camera.Shake": return Add("ShakeCamera", ("amplitude", Lit(0)), ("frames", Lit(1)));
                            case "Save.Read": return Add("LoadGame", ("slot", Lit(0)));
                            case "Scene.SetTile": return Add("SetTile", ("layer", Lit(0)), ("x", Lit(1)), ("y", Lit(2)), ("tile", Lit(3)));
                            case "Camera.Follow":
                                {
                                    var follow = Add("CameraFollow");
                                    ActorInput(args[0], follow.Id, "target");
                                    return follow;
                                }
                        }
                        if (inv.Expression is MemberAccessExpressionSyntax { Name.Identifier.ValueText: "SetVelocity" or "AddForce" } sv && BodyOf(sv.Expression) is { } svBody)
                        {
                            var n = Add(sv.Name.Identifier.ValueText);
                            ValueInput(args[0], n.Id, "x", "x");
                            ValueInput(args[1], n.Id, "y", "y");
                            return Target(n, svBody);
                        }
                        if (inv.Expression is MemberAccessExpressionSyntax { Name.Identifier.ValueText: "Destroy" } d)
                        {
                            var n = Add("Destroy");
                            ActorInput(d.Expression, n.Id, "actor");
                            return n;
                        }
                        break;
                    }
            }
            throw new FormatException($"'{e}' is not a graph action.");
        }

        // "body" (the graph's actor) or "x.Get<PlatformerBody>()" (the actor wired to Target); null for anything else.
        static ExpressionSyntax? BodyOf(ExpressionSyntax e) =>
            e.ToString() == "body" ? e
            : e is InvocationExpressionSyntax { Expression: MemberAccessExpressionSyntax { Name: GenericNameSyntax { Identifier.ValueText: "Get" } g } } && g.TypeArgumentList.Arguments.ToString() == "PlatformerBody" ? e
            : null;

        static ExpressionSyntax? Vy(ExpressionSyntax left) =>
            left is MemberAccessExpressionSyntax { Name.Identifier.ValueText: "vy" } ma ? BodyOf(ma.Expression) : null;

        GraphNode Target(GraphNode n, ExpressionSyntax body)
        {
            if (body is InvocationExpressionSyntax { Expression: MemberAccessExpressionSyntax owner }) ActorInput(owner.Expression, n.Id, "target");
            return n;
        }

        GraphNode WithValue(string type, ExpressionSyntax value, string pin, params (string, string)[] props)
        {
            var n = Add(type, props);
            ValueInput(value, n.Id, pin, pin);
            return n;
        }

        void ActorInput(ExpressionSyntax e, string node, string pin)
        {
            switch (e.ToString())
            {
                case "other":
                    var touch = G.Nodes.First(n => n.Type == "OnTouch");
                    Link(touch.Id, "other", node, pin);
                    return;
                case "actor":
                    return;
                default:
                    throw new FormatException($"'{e}' is not an actor of the graph.");
            }
        }

        /// <summary>Connects an expression to an input pin: literals become the node's prop, others value nodes.</summary>
        void ValueInput(ExpressionSyntax e, string node, string pin, string? prop)
        {
            while (e is ParenthesizedExpressionSyntax p) e = p.Expression;
            var text = e.ToString();
            if (prop != null && (e is LiteralExpressionSyntax || e is PrefixUnaryExpressionSyntax { RawKind: (int)SyntaxKind.UnaryMinusExpression, Operand: LiteralExpressionSyntax }))
            {
                G.Node(node)!.Props[prop] = text;
                return;
            }
            var v = Value(e);
            Link(v.Id, "value", node, pin);
        }

        GraphNode Value(ExpressionSyntax e)
        {
            while (e is ParenthesizedExpressionSyntax p) e = p.Expression;
            switch (e)
            {
                case InvocationExpressionSyntax range when range.Expression.ToString() == "Random.Range" && range.ArgumentList.Arguments.Count == 2:
                    return Add("RandomRange", ("lo", range.ArgumentList.Arguments[0].ToString()), ("hi", range.ArgumentList.Arguments[1].ToString()));
                case InvocationExpressionSyntax exists when exists.Expression.ToString() == "Save.Exists" && exists.ArgumentList.Arguments.Count == 1:
                    return Add("SaveExists", ("slot", exists.ArgumentList.Arguments[0].ToString()));
                case InvocationExpressionSyntax inv when inv.Expression.ToString() is "Input.Pressed" or "Input.Held" or "Input.Released":
                    {
                        var type = inv.Expression.ToString() switch { "Input.Pressed" => "ButtonPressed", "Input.Held" => "ButtonHeld", _ => "ButtonReleased" };
                        var key = inv.ArgumentList.Arguments[0].Expression.ToString().Replace("Key.", "");
                        return Add(type, ("button", key));
                    }
                case BinaryExpressionSyntax bin when bin.IsKind(SyntaxKind.LogicalAndExpression) || bin.IsKind(SyntaxKind.LogicalOrExpression):
                    {
                        var n = Add(bin.IsKind(SyntaxKind.LogicalAndExpression) ? "And" : "Or");
                        ValueInput(bin.Left, n.Id, "a", null);
                        ValueInput(bin.Right, n.Id, "b", null);
                        return n;
                    }
                case BinaryExpressionSyntax bin when bin.OperatorToken.ValueText is "+" or "-" or "*":
                    {
                        var n = Add(bin.OperatorToken.ValueText switch { "+" => "Add", "-" => "Subtract", _ => "Multiply" });
                        ValueInput(bin.Left, n.Id, "a", "a");
                        ValueInput(bin.Right, n.Id, "b", "b");
                        return n;
                    }
                case BinaryExpressionSyntax bin when bin.OperatorToken.ValueText is ">" or "<" or ">=" or "<=" or "==" or "!=":
                    {
                        var n = Add("Compare", ("op", bin.OperatorToken.ValueText));
                        ValueInput(bin.Left, n.Id, "a", "a");
                        ValueInput(bin.Right, n.Id, "b", "b");
                        return n;
                    }
                case PrefixUnaryExpressionSyntax u when u.IsKind(SyntaxKind.LogicalNotExpression):
                    {
                        var n = Add("Not");
                        ValueInput(u.Operand, n.Id, "a", null);
                        return n;
                    }
                case MemberAccessExpressionSyntax ma when ma.Expression is IdentifierNameSyntax { Identifier.ValueText: "Game" }:
                    return Add("GetVariable", ("variable", ma.Name.Identifier.ValueText));
                case MemberAccessExpressionSyntax ma when ma.Name.Identifier.ValueText is "OnGround" or "Velocity" && BodyOf(ma.Expression) is { } vb:
                    return Target(Add(ma.Name.Identifier.ValueText == "OnGround" ? "IsOnGround" : "GetVelocity"), vb);
                case ObjectCreationExpressionSyntax oc when oc.Type.ToString() == "fixed2" && oc.ArgumentList is { Arguments.Count: 2 } va:
                    {
                        var n = Add("VectorFromVelocity");
                        ValueInput(va.Arguments[0].Expression, n.Id, "vx", "vx");
                        ValueInput(va.Arguments[1].Expression, n.Id, "vy", "vy");
                        return n;
                    }
            }
            return e.ToString() switch
            {
                "Input.AxisX" => Add("AxisX"),
                "Input.AxisY" => Add("AxisY"),
                "Input.AnyKey" => Add("AnyKey"),
                "body.vx" => Add("VelocityX"),
                "body.vy" => Add("VelocityY"),
                "actor" => Add("Self"),
                _ => throw new FormatException($"'{e}' is not a graph value."),
            };
        }
    }

    /// <summary>Columns by link depth, rows in creation order (used when there is no previous graph).</summary>
    static void Layout(LogicGraph g)
    {
        var depth = g.Nodes.ToDictionary(n => n.Id, _ => 0);
        for (var pass = 0; pass < g.Nodes.Count; pass++)
            foreach (var l in g.Links)
                if (depth.TryGetValue(l.FromNode, out var d) && depth[l.ToNode] < d + 1) depth[l.ToNode] = d + 1;
        var rows = new Dictionary<int, int>();
        foreach (var n in g.Nodes)
        {
            var col = depth[n.Id];
            rows.TryGetValue(col, out var row);
            rows[col] = row + 1;
            n.X = 40 + col * 240;
            n.Y = 40 + row * 110;
        }
    }

    /// <summary>Keeps ids, positions and prop text of the previous graph for nodes in the same place of the code.</summary>
    static void Merge(LogicGraph g, LogicGraph previous, List<string> order)
    {
        GraphCodeGen.Generate(previous, previous.Class, out var prevOrder);
        if (prevOrder.Count != order.Count) return;
        var rename = new Dictionary<string, string>();
        for (var i = 0; i < order.Count; i++)
        {
            var n = g.Node(order[i])!;
            var p = previous.Node(prevOrder[i]);
            if (p == null || p.Type != n.Type) return;
            rename[n.Id] = p.Id;
        }
        foreach (var n in g.Nodes)
        {
            var p = previous.Node(rename[n.Id])!;
            n.Id = p.Id;
            n.X = p.X;
            n.Y = p.Y;
            foreach (var (k, v) in p.Props)
                if (!n.Props.TryGetValue(k, out var nv) || SameValue(nv, v)) n.Props[k] = v;
        }
        g.Links = g.Links.Select(l => new GraphLink(rename[l.FromNode] + "." + l.FromPin, rename[l.ToNode] + "." + l.ToPin)).ToList();
        // Keep the previous order of nodes in the file.
        g.Nodes = g.Nodes.OrderBy(n => previous.Nodes.FindIndex(p => p.Id == n.Id)).ToList();
        g.Links = g.Links.OrderBy(l => previous.Links.FindIndex(p => p == l) is var i && i < 0 ? int.MaxValue : i).ToList();
    }

    static bool SameValue(string a, string b)
    {
        if (double.TryParse(a, NumberStyles.Float, CultureInfo.InvariantCulture, out var x) && double.TryParse(b, NumberStyles.Float, CultureInfo.InvariantCulture, out var y))
            return x == y;
        return Names.StripExtension(a) == Names.StripExtension(b);
    }
