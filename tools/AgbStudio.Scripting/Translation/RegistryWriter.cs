using System.Globalization;
using System.Text;
using AgbStudio.Core.Project;
using AgbStudio.Scripting.Bytecode;
using Microsoft.CodeAnalysis;
using BuildCpp = AgbStudio.Build.Pipeline.Cpp;

namespace AgbStudio.Scripting.Translation;

/// <summary>
/// agb_scripts.hpp / agb_scripts.cpp: behaviour factories and Init structs, the script and native tables of the
/// Event Script VM, project natives (Game fields), paths and names, scene hooks and agb_scripts_init().
/// </summary>
internal sealed class RegistryWriter
{
    readonly ScriptModel _m;
    readonly ScriptCompileContext _ctx;
    readonly ScriptTables _tables;
    readonly List<TypeOutput> _types;
    readonly OpcodeTable _ops;
    readonly List<ScriptVarDef> _vars;  // project variables and flags created by dialogues

    public RegistryWriter(ScriptModel m, ScriptCompileContext ctx, ScriptTables tables, List<TypeOutput> types, OpcodeTable ops, List<ScriptVarDef> vars)
    {
        _m = m;
        _ctx = ctx;
        _tables = tables;
        _types = types;
        _ops = ops;
        _vars = vars;
    }

    IEnumerable<TypeOutput> Behaviours => _types.Where(t => t.Role == TypeRole.Behaviour && !t.Abstract && t.Emitted);

    TypeOutput? SceneScriptFor(string scene) =>
        _types.FirstOrDefault(t => t.Role == TypeRole.SceneScript && !t.Abstract && (t.Name == scene || t.Name == BuildCpp.Ident(scene)));

    SceneEventsDef? EventsFor(string scene) => _ctx.SceneEvents.FirstOrDefault(e => e.Scene == scene);

    bool HasEventClass(string scene)
    {
        var e = EventsFor(scene);
        return e != null && (e.OnLoad.Trim().Length + e.OnEnter.Trim().Length + e.OnExit.Trim().Length > 0 || e.LinkConditions.Count > 0);
    }

    public string Header()
    {
        var sb = new StringBuilder();
        sb.Append("// Generated by AGB Studio. Do not edit. Registry of the C# scripts: factories for scene actors, cutscene ids,\n");
        sb.Append("// scene hooks and agb_scripts_init() for GameDef.init.\n#pragma once\n#include \"agb_prelude.hpp\"\n");
        foreach (var e in Behaviours.SelectMany(b => b.Fields).Where(f => f.EnumCpp != null).Select(f => f.EnumCpp!).Distinct())
        {
            var t = _types.FirstOrDefault(x => x.CppName == e);
            if (t != null) sb.Append($"#include \"{t.Name}.hpp\"\n");
        }
        sb.Append("\n// Ids of [Cutscene] methods and dialogue conversations in the script table.\nnamespace agb_cutscene {\n");
        foreach (var s in _tables.Scripts) sb.Append($"constexpr agb::u16 {s.Symbol["agb_cutscene::".Length..]} = {s.Id};\n");
        sb.Append("}  // namespace agb_cutscene\n\n");

        sb.Append("// Behaviours: agb_make_<Class>(arena) uses the defaults of the C# field initializers;\n");
        sb.Append("// agb_make_<Class>_with(arena, agb_init_<Class>{.field = value, ...}) applies Inspector values (declaration order).\n");
        sb.Append("// The default values live in agb_defaults.cpp, so changing one recompiles that small file, not every scene and script.\n");
        foreach (var b in Behaviours)
        {
            foreach (var f in b.Fields.Where(f => f.InitCpp != null)) sb.Append($"extern const {f.CppType} agb_default_{b.Name}_{f.CppName};\n");
            sb.Append($"struct agb_init_{b.Name} {{\n");
            foreach (var f in b.Fields.Where(f => f.InitCpp != null)) sb.Append($"    {f.CppType} {f.CppName} = agb_default_{b.Name}_{f.CppName};\n");
            sb.Append("};\n");
            sb.Append($"agb::Behaviour* agb_make_{b.Name}(agb::Arena& arena);\n");
            sb.Append($"agb::Behaviour* agb_make_{b.Name}_with(agb::Arena& arena, const agb_init_{b.Name}& init);\n");
        }
        sb.Append("""

            // All script behaviours by name (scene tools, hot reload).
            struct agb_ScriptType {
                const char* name;
                agb::u16 typeId;
                agb::BehaviourCreate create;
            };
            extern const agb_ScriptType agb_script_types[];
            extern const int agb_script_type_count;
            agb::BehaviourCreate agb_find_behaviour(const char* name);

            // Generic Inspector values: field index (as fieldName(i)) and raw value (int, fixed raw or 0 / 1).
            struct agb_FieldValue {
                agb::u8 index;
                agb::s32 raw;
            };
            bool agb_set_field(agb::Behaviour* behaviour, int index, agb::s32 raw);
            agb::Behaviour* agb_make_with(agb::BehaviourCreate create, agb::Arena& arena, const agb_FieldValue* values, int count);

            // GameDef.init: registers the script and native tables, paths, names, the persistent flag / variable store and
            // the Debugger file / method names.
            void agb_scripts_init();

            """.Replace("\r\n", "\n"));
        var cells = DbScripts.Cells(_ctx);
        if (cells.Count > 0)
        {
            sb.Append("// Database cells of type script (the table's void (*)() members).\n");
            foreach (var c in cells) sb.Append($"void {DbScripts.Symbol(c)}();\n");
        }
        sb.Append("// Scene hooks for SceneDef.onLoad / onEnter / onExit (Scene Settings events, then the SceneScript of the same name).\n");
        foreach (var scene in _ctx.Scenes.OrderBy(s => s.Value).Select(s => s.Key))
        {
            var id = BuildCpp.Ident(scene);
            sb.Append($"void agb_scene_{id}_onLoad();\nvoid agb_scene_{id}_onEnter();\nvoid agb_scene_{id}_onExit();\n");
            foreach (var link in EventsFor(scene)?.LinkConditions.Keys.Order() ?? Enumerable.Empty<int>())
                sb.Append($"bool agb_link_{id}_{link}();  // LinkDef.condition (\"Only if\")\n");
        }
        return sb.ToString();
    }

    /// <summary>agb_defaults.cpp: the defaults of the behaviours' Inspector fields (agb_init_&lt;Class&gt;), kept apart so a
    /// changed default recompiles one small file (G-PERF.02).</summary>
    public string Defaults()
    {
        var sb = new StringBuilder("// Generated by AGB Studio. Do not edit.\n#include \"agb_scripts.hpp\"\n\n");
        foreach (var b in Behaviours)
            foreach (var f in b.Fields.Where(f => f.InitCpp != null)) sb.Append($"extern const {f.CppType} agb_default_{b.Name}_{f.CppName} = {f.InitCpp};\n");
        return sb.ToString();
    }

    public string Source()
    {
        var sb = new StringBuilder();
        sb.Append("// Generated by AGB Studio. Do not edit.\n#include \"agb_scripts.hpp\"\n");
        var includes = new SortedSet<string>(StringComparer.Ordinal);
        foreach (var n in _tables.UserNatives) includes.Add(n.ContainingType.Name);
        foreach (var scene in _ctx.Scenes.Keys)
        {
            if (SceneScriptFor(scene) is { } t) includes.Add(t.Name);
            if (HasEventClass(scene)) includes.Add("SceneEvents_" + BuildCpp.Ident(scene));
        }
        foreach (var t in DbScripts.Cells(_ctx).Select(c => c.Table).Distinct()) includes.Add(DbScripts.ClassName(t));
        foreach (var i in includes) sb.Append($"#include \"{i}.hpp\"\n");
        sb.Append("\nnamespace {\n");

        // ---- bytecode ----
        foreach (var s in _tables.Scripts)
        {
            sb.Append($"// {s.Name} ({s.File}:{s.Line})\nconst agb::u8 kScript{s.Id}[] = {{");
            for (var i = 0; i < s.Code.Length; i++)
            {
                if (i % 16 == 0) sb.Append("\n    ");
                sb.Append(s.Code[i].ToString(CultureInfo.InvariantCulture)).Append(i + 1 < s.Code.Length ? ", " : "");
            }
            if (s.Code.Length == 0) sb.Append(_ops["End"].Code);
            sb.Append("\n};\n");
        }
        if (_tables.Scripts.Count > 0)
        {
            sb.Append("const agb::script::Script kScripts[] = {\n");
            foreach (var s in _tables.Scripts)
                sb.Append($"    {{{Names.CppString(s.Name)}, kScript{s.Id}, sizeof kScript{s.Id}, {s.Locals}, {s.Args}}},\n");
            sb.Append("};\n");
        }

        // ---- project natives: Game fields and [ScriptNative] wrappers ----
        GameNatives(sb);
        foreach (var m in _tables.UserNatives) UserNative(sb, m);
        sb.Append("const agb::script::Native kNatives[] = {\n    AGB_BUILTIN_NATIVES(AGB_NATIVE_ENTRY)\n");
        foreach (var n in _tables.Natives.Skip(_tables.BuiltinCount))
            sb.Append($"    {{{Names.CppString(n.Name.StartsWith("User.", StringComparison.Ordinal) ? n.Name[5..] : n.Name)}, {n.CppFunction}, {(n.Waits ? "true" : "false")}}},\n");
        sb.Append("};\n");

        // ---- names, paths, persistent store ----
        if (_tables.Names.Count > 0)
            sb.Append($"const char* const kNames[] = {{{string.Join(", ", _tables.Names.Select(Names.CppString))}}};\n");
        for (var i = 0; i < _ctx.Paths.Count; i++)
            sb.Append($"const agb::s16 kPath{i}[] = {{{string.Join(", ", _ctx.Paths[i].Points.SelectMany(p => p.Take(2)).DefaultIfEmpty(0))}}};\n");
        if (_ctx.Paths.Count > 0)
        {
            sb.Append("const agb::script::natives::MovePath kPaths[] = {\n");
            for (var i = 0; i < _ctx.Paths.Count; i++)
            {
                var p = _ctx.Paths[i];
                sb.Append($"    {{kPath{i}, {p.Points.Count}, {(p.Relative ? "true" : "false")}, agb::fixed::fromRaw({(int)Math.Round(p.Speed * 256)})}},\n");
            }
            sb.Append("};\n");
        }
        var vars = _vars.Where(v => v.Id < 0x4000).ToList();
        var flagCount = Math.Max(1, vars.Where(v => v.Type == "bool").Select(v => v.Id + 1).DefaultIfEmpty(0).Max());
        var varCount = Math.Max(1, vars.Where(v => v.Type != "bool").Select(v => v.Id + 1).DefaultIfEmpty(0).Max());
        // Persistent flags and variables (ids below 0x4000) are saved: they live in GameState::scriptStore.
        flagCount = Math.Min(flagCount, 256);
        varCount = Math.Min(varCount, 32);
        // Debugger names (agb/probe.hpp): AGB_PROBE / AGB_SCOPE ids index these tables.
        var files = _m.FileIds.OrderBy(f => f.Value).Select(f => Path.GetFileName(f.Key)).DefaultIfEmpty("").Select(Names.CppString);
        sb.Append($"const char* const kDebugFiles[] = {{{string.Join(", ", files)}}};\n");
        sb.Append($"const char* const kDebugMethods[] = {{{string.Join(", ", _m.MethodNames.DefaultIfEmpty("").Select(Names.CppString))}}};\n");
        var sceneObjects = _ctx.Scenes.Keys.Select(SceneScriptFor).OfType<TypeOutput>().Distinct().ToList();
        foreach (var t in sceneObjects) sb.Append($"{t.CppName} g_scene_{t.Name};\n");
        sb.Append("}  // namespace\n\n");

        // ---- registry ----
        var behaviours = Behaviours.ToList();
        sb.Append("const agb_ScriptType agb_script_types[] = {\n");
        foreach (var b in behaviours) sb.Append($"    {{{Names.CppString(b.Name)}, {64 + b.TypeIndex}, agb_make_{b.Name}}},\n");
        if (behaviours.Count == 0) sb.Append("    {\"\", 0, nullptr},\n");
        sb.Append($"}};\nconst int agb_script_type_count = {behaviours.Count};\n");
        sb.Append("""

            agb::BehaviourCreate agb_find_behaviour(const char* name) {
                for (int i = 0; i < agb_script_type_count; ++i) {
                    const char* a = agb_script_types[i].name;
                    const char* b = name;
                    while (*a && *a == *b) ++a, ++b;
                    if (*a == *b) return agb_script_types[i].create;
                }
                return nullptr;
            }

            bool agb_set_field(agb::Behaviour* behaviour, int index, agb::s32 raw) {
                if (!behaviour || index < 0 || index >= behaviour->fieldCount()) return false;
                void* p = behaviour->fieldPtr(index);
                if (!p) return false;
                switch (behaviour->fieldKind(index)) {
                    case 1: static_cast<agb::fixed*>(p)->raw = raw; break;
                    case 2: *static_cast<bool*>(p) = raw != 0; break;
                    default: *static_cast<agb::s32*>(p) = raw; break;
                }
                return true;
            }

            agb::Behaviour* agb_make_with(agb::BehaviourCreate create, agb::Arena& arena, const agb_FieldValue* values, int count) {
                agb::Behaviour* b = create ? create(arena) : nullptr;
                for (int i = 0; b && i < count; ++i) agb_set_field(b, values[i].index, values[i].raw);
                return b;
            }

            """.Replace("\r\n", "\n"));
        sb.Append("void agb_scripts_init() {\n");
        sb.Append(_tables.Scripts.Count > 0
            ? $"    agb::script::setTables(kScripts, {_tables.Scripts.Count}, kNatives, {_tables.Natives.Count});\n"
            : $"    agb::script::setTables(nullptr, 0, kNatives, {_tables.Natives.Count});\n");
        sb.Append($"    agb::script::setPersistentStore(agb_state.scriptStore.flags, {flagCount}, agb_state.scriptStore.vars, {varCount});\n");
        if (_ctx.Paths.Count > 0) sb.Append($"    agb::script::natives::setPaths(kPaths, {_ctx.Paths.Count});\n");
        if (_tables.Names.Count > 0) sb.Append($"    agb::script::natives::setNames(kNames, {_tables.Names.Count});\n");
        sb.Append("    agb::dbg::setNames(kDebugFiles, kDebugMethods);\n");
        sb.Append("}\n");

        // ---- database script cells ----
        foreach (var c in DbScripts.Cells(_ctx))
            sb.Append($"\nvoid {DbScripts.Symbol(c)}() {{ ::AgbGenerated::{DbScripts.ClassName(c.Table)}::{DbScripts.Method(c)}(); }}\n");

        // ---- scene hooks ----
        foreach (var scene in _ctx.Scenes.OrderBy(s => s.Value).Select(s => s.Key))
        {
            var id = BuildCpp.Ident(scene);
            var ss = SceneScriptFor(scene);
            var ev = EventsFor(scene);
            foreach (var hook in new[] { "OnLoad", "OnEnter", "OnExit" })
            {
                var body = new StringBuilder();
                if (hook == "OnLoad") body.Append("    agb::script::natives::reset();\n");
                if (hook == "OnLoad" && ss != null) body.Append($"    g_scene_{ss.Name} = {ss.CppName}();\n");
                var text = hook switch { "OnLoad" => ev?.OnLoad, "OnEnter" => ev?.OnEnter, _ => ev?.OnExit } ?? "";
                if (text.Trim().Length > 0) body.Append($"    ::AgbGenerated::SceneEvents_{id}::{hook}();\n");
                if (ss != null && ss.SceneEvents.Contains(hook)) body.Append($"    g_scene_{ss.Name}.{hook}();\n");
                sb.Append($"\nvoid agb_scene_{id}_{char.ToLowerInvariant(hook[0])}{hook[1..]}() {{\n{body}}}\n");
            }
            foreach (var link in ev?.LinkConditions.Keys.Order() ?? Enumerable.Empty<int>())
                sb.Append($"\nbool agb_link_{id}_{link}() {{ return ::AgbGenerated::SceneEvents_{id}::Link{link}(); }}\n");
        }
        return sb.ToString();
    }

    void GameNatives(StringBuilder sb)
    {
        var get = new StringBuilder();
        var set = new StringBuilder();
        for (var i = 0; i < _ctx.SaveFields.Count; i++)
        {
            var f = _ctx.SaveFields[i];
            var n = "agb_state." + BuildCpp.Ident(f.Name);
            switch (f.Type.Trim())
            {
                case "int":
                    get.Append($"        case {i}: return {n};\n");
                    set.Append($"        case {i}: {n} = args[1]; break;\n");
                    break;
                case "byte":
                    get.Append($"        case {i}: return {n};\n");
                    set.Append($"        case {i}: {n} = static_cast<unsigned char>(args[1]); break;\n");
                    break;
                case "short":
                    get.Append($"        case {i}: return {n};\n");
                    set.Append($"        case {i}: {n} = static_cast<short>(args[1]); break;\n");
                    break;
                case "fixed":
                    get.Append($"        case {i}: return {n}.raw;\n");
                    set.Append($"        case {i}: {n} = agb::fixed::fromRaw(args[1]); break;\n");
                    break;
                case "bool":
                    get.Append($"        case {i}: return {n} ? 1 : 0;\n");
                    set.Append($"        case {i}: {n} = args[1] != 0; break;\n");
                    break;
            }
        }
        sb.Append("// Game fields for cutscenes: GameGet(field), GameSet(field, value).\n");
        sb.Append("agb::s32 agbgen_native_GameGet(agb::script::Context& ctx, const agb::s32* args, int argc) {\n    AGB_UNUSED(ctx);\n");
        sb.Append("    if (argc < 1) return 0;\n");
        if (get.Length > 0) sb.Append("    switch (args[0]) {\n").Append(get).Append("        default: return 0;\n    }\n");
        else sb.Append("    AGB_UNUSED(args);\n    return 0;\n");
        sb.Append("}\n");
        sb.Append("agb::s32 agbgen_native_GameSet(agb::script::Context& ctx, const agb::s32* args, int argc) {\n    AGB_UNUSED(ctx);\n");
        sb.Append("    if (argc < 2) return 0;\n");
        if (set.Length > 0) sb.Append("    switch (args[0]) {\n").Append(set).Append("        default: break;\n    }\n");
        sb.Append("    return args[1];\n}\n");
    }

    void UserNative(StringBuilder sb, IMethodSymbol m)
    {
        var waits = ScriptModel.NativeWaits(m) == true;
        var name = $"agbgen_native_{Names.Identifier(m.ContainingType.Name)}_{Names.Identifier(m.Name)}";
        sb.Append($"agb::s32 {name}(agb::script::Context& ctx, const agb::s32* args, int argc) {{\n");
        if (!waits) sb.Append("    AGB_UNUSED(ctx);\n");
        sb.Append("    AGB_UNUSED(argc);\n");
        if (m.Parameters.Length == 0) sb.Append("    AGB_UNUSED(args);\n");
        var args = m.Parameters.Select((p, i) => _m.IsFixed(p.Type) ? $"agb::fixed::fromRaw(args[{i}])"
            : p.Type.SpecialType == SpecialType.System_Boolean ? $"args[{i}] != 0"
            : p.Type.TypeKind == TypeKind.Enum ? $"static_cast<{_m.CppTypeName((INamedTypeSymbol)p.Type)}>(args[{i}])"
            : $"static_cast<{_m.CppType(p.Type) ?? "agb::s32"}>(args[{i}])");
        var call = $"{_m.CppTypeName(m.ContainingType)}::{Names.Cpp(m.Name)}({string.Join(", ", args)})";
        string ret;
        if (m.ReturnsVoid)
        {
            sb.Append($"    {call};\n");
            ret = "0";
        }
        else
        {
            sb.Append($"    const auto r = {call};\n");
            ret = _m.IsFixed(m.ReturnType) ? "r.raw" : m.ReturnType.SpecialType == SpecialType.System_Boolean ? "r ? 1 : 0" : "static_cast<agb::s32>(r)";
        }
        if (waits) sb.Append("    agb::script::natives::waitForResume(ctx);\n");
        sb.Append($"    return {ret};\n}}\n");
    }
}
