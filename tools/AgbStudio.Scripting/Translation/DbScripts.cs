using System.Globalization;
using System.Text;
using System.Text.RegularExpressions;
using AgbStudio.Core.Project;
using BuildCpp = AgbStudio.Build.Pipeline.Cpp;

namespace AgbStudio.Scripting.Translation;

/// <summary>
/// Database cells of type "script" ("score += 10", "Heal(power)"): each becomes a static C# method (row values as
/// locals, Game fields by name, Heal / Damage on the player) and a C++ function
/// <c>void agb_dbscript_&lt;Table&gt;_&lt;Row&gt;_&lt;Field&gt;()</c> that the database table points at.
/// </summary>
internal static class DbScripts
{
    public sealed record Cell(TableFile Table, string RowId, FieldDef Field, string Code, Dictionary<string, string> Row);

    public static List<Cell> Cells(ScriptCompileContext ctx) =>
        ctx.Tables.SelectMany(t => t.Rows.SelectMany(r => t.Fields.Where(f => f.Type == "script")
                .Select(f => (r, f, code: (r.GetValueOrDefault(f.Name) ?? "").Trim()))
                .Where(x => x.code.Length > 0)
                .Select(x => new Cell(t, x.r.GetValueOrDefault(t.KeyField) ?? "", x.f, x.code, x.r))))
            .ToList();

    public static string Symbol(Cell c) => $"agb_dbscript_{BuildCpp.Ident(c.Table.Name)}_{BuildCpp.Ident(c.RowId)}_{BuildCpp.Ident(c.Field.Name)}";
    public static string ClassName(TableFile t) => "DbScripts_" + BuildCpp.Ident(t.Name);
    public static string Method(Cell c) => $"{BuildCpp.Ident(c.RowId)}_{BuildCpp.Ident(c.Field.Name)}";

    /// <summary>Fully qualified names of the project's <c>[DatabaseActions]</c> classes (their static methods are
    /// callable by name from cells).</summary>
    public static List<string> ActionClasses(IEnumerable<string> sources)
    {
        var list = new List<string>();
        foreach (var text in sources)
        {
            var ns = Regex.Match(text, @"^\s*namespace\s+([\w.]+)", RegexOptions.Multiline);
            foreach (Match m in Regex.Matches(text, @"\[DatabaseActions(?:Attribute)?\]\s*(?:(?:public|internal|static|partial)\s+)*class\s+(\w+)"))
                list.Add((ns.Success ? ns.Groups[1].Value + "." : "") + m.Groups[1].Value);
        }
        return list;
    }

    // "8s" in a cell is 8 seconds, as in Scene Settings events.
    static string Seconds(string text) => Regex.Replace(text, @"(?<![\w.])(\d+(?:\.\d+)?)s\b", "$1");

    public static string? Source(ScriptCompileContext ctx, IReadOnlyList<string>? actionClasses = null)
    {
        var cells = Cells(ctx);
        if (cells.Count == 0) return null;
        var sb = new StringBuilder("// <auto-generated/>\n#pragma warning disable\nusing GBA;\nusing static GBA.Game;\n");
        foreach (var c in actionClasses ?? []) sb.Append($"using static global::{c};\n");
        sb.Append("\nnamespace AgbGenerated\n{\n");
        foreach (var group in cells.GroupBy(c => c.Table))
        {
            var t = group.Key;
            sb.Append($"    public sealed class {ClassName(t)} : ScriptBase\n    {{\n");
            sb.Append("        static void Heal(int amount) { var p = Player; if (p != null) { var h = p.Get<Health>(); if (h != null) h.Heal(amount); } }\n");
            sb.Append("        static void Damage(int amount) { var p = Player; if (p != null) { var h = p.Get<Health>(); if (h != null) h.Damage(amount); } }\n");
            // Fixed columns ("power") work too: Heal(power) heals the rounded amount.
            sb.Append("        static void Heal(Fixed amount) { Heal(amount.Round()); }\n");
            sb.Append("        static void Damage(Fixed amount) { Damage(amount.Round()); }\n");
            foreach (var c in group)
            {
                var locals = new StringBuilder();
                foreach (var f in t.Fields.Where(f => f.Name != t.KeyField))
                {
                    var raw = (c.Row.GetValueOrDefault(f.Name) ?? f.Default ?? "").Trim();
                    var name = ProjectApi.CsIdent(f.Name);
                    switch (f.Type)
                    {
                        case "int" when int.TryParse(raw.Length > 0 ? raw : "0", NumberStyles.Integer, CultureInfo.InvariantCulture, out var i):
                            locals.Append($"int {name} = {i}; ");
                            break;
                        case "fixed" when double.TryParse(raw.Length > 0 ? raw : "0", NumberStyles.Float, CultureInfo.InvariantCulture, out var d):
                            locals.Append($"Fixed {name} = {Names.Decimal(d)}; ");
                            break;
                        case "bool":
                            locals.Append($"bool {name} = {(raw.Equals("true", StringComparison.OrdinalIgnoreCase) || raw is "1" or "yes" ? "true" : "false")}; ");
                            break;
                    }
                }
                var code = Seconds(c.Code.EndsWith(';') || c.Code.EndsWith('}') ? c.Code : c.Code + ";");
                sb.Append($"#line 1 \"data/{t.Name}.db\"\n");
                sb.Append($"        public static void {Method(c)}() {{ {locals}{code} }}\n#line default\n");
            }
            sb.Append("    }\n");
        }
        sb.Append("}\n");
        return sb.ToString();
    }
}
