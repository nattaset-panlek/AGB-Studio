using System.Text;
using System.Text.Json;

namespace AgbStudio.Scripting;

/// <summary>
/// P14.02: writes &lt;Project&gt;.csproj, an .editorconfig with the GAE severities and .vscode settings, so VS Code, Rider and
/// Visual Studio show IntelliSense for the GBA API and the same GAE diagnostics and code fixes as the built-in Script
/// Editor. The API reference assembly, its XML docs and the analyzers are copied to build/ide/ next to the generated
/// project API. The game itself is still built by AGB Studio; this project only serves the IDE.
/// </summary>
public static class CsprojGenerator
{
    public const string IdeDir = "build/ide";

    public static string ProjectFile(string root, string projectName) =>
        Path.Combine(root, Names.Identifier(projectName) + ".csproj");

    /// <summary>Writes the IDE files (only files whose content changed). Returns the files written.</summary>
    public static List<string> Write(string root, string projectName, ScriptCompileContext ctx, ScriptCompileResult? compiled = null,
        string targetFramework = "netstandard2.0")
    {
        var written = new List<string>();
        void Put(string rel, string text)
        {
            var path = Path.Combine(root, rel);
            text = text.Replace("\r\n", "\n");
            if (File.Exists(path) && File.ReadAllText(path) == text) return;
            Directory.CreateDirectory(Path.GetDirectoryName(path)!);
            File.WriteAllText(path, text, new UTF8Encoding(false));
            written.Add(path);
        }
        void Copy(string from, string relTo)
        {
            if (!File.Exists(from)) return;
            var to = Path.Combine(root, relTo);
            if (File.Exists(to) && new FileInfo(to).Length == new FileInfo(from).Length && File.GetLastWriteTimeUtc(to) >= File.GetLastWriteTimeUtc(from)) return;
            Directory.CreateDirectory(Path.GetDirectoryName(to)!);
            File.Copy(from, to, true);
            written.Add(to);
        }

        Copy(ApiReference.ApiAssemblyPath, $"{IdeDir}/sdk/AgbStudio.Api.dll");
        Copy(ApiReference.ApiDocumentationPath, $"{IdeDir}/sdk/AgbStudio.Api.xml");
        Copy(ApiReference.AnalyzerAssemblyPath, $"{IdeDir}/sdk/AgbStudio.Analyzers.dll");
        Copy(ApiReference.CodeFixAssemblyPath, $"{IdeDir}/sdk/AgbStudio.Analyzers.CodeFixes.dll");
        Put($"{IdeDir}/{ProjectApi.CSharpFileName}", compiled?.ProjectApiSource ?? ProjectApi.CSharp(ctx, ctx.Vars));
        // Dialogue classes, so scripts that start a conversation also bind in the IDE.
        foreach (var (src, code) in compiled?.GeneratedCSharp ?? new Dictionary<string, string>())
            if (src.EndsWith(".dlg", StringComparison.OrdinalIgnoreCase))
                Put($"{IdeDir}/{Path.GetFileNameWithoutExtension(src)}.dlg.g.cs", code);

        var ns = ctx.Namespace.Length > 0 ? ctx.Namespace : Names.Identifier(projectName);
        var csproj = $"""
            <Project Sdk="Microsoft.NET.Sdk">
              <!-- Generated by AGB Studio for external editors: IntelliSense for the GBA API and the GAE rules.
                   Regenerated when scripts change. The game is built by AGB Studio, not by this project.
                   The fixed-point type is spelled Fixed here (fixed is a reserved word in standard C#). -->
              <PropertyGroup>
                <TargetFramework>{targetFramework}</TargetFramework>
                <LangVersion>latest</LangVersion>
                <Nullable>disable</Nullable>
                <ImplicitUsings>disable</ImplicitUsings>
                <EnableDefaultItems>false</EnableDefaultItems>
                <RootNamespace>{ns}</RootNamespace>
                <AssemblyName>{Names.Identifier(projectName)}.Scripts</AssemblyName>
                <TreatWarningsAsErrors>{(ctx.Analyzer.TreatWarningsAsErrors ? "true" : "false")}</TreatWarningsAsErrors>
                <NoWarn>$(NoWarn);CS1998;CS0414;CS0169;CS4014</NoWarn>
                <BaseOutputPath>{IdeDir}/bin/</BaseOutputPath>
                <GenerateAssemblyInfo>false</GenerateAssemblyInfo>
              </PropertyGroup>
              <ItemGroup>
                <Compile Include="scripts/**/*.cs" />
                <Compile Include="{IdeDir}/*.g.cs" />
                <None Include="scripts/**/*.graph;dialogue/**/*.dlg" />
              </ItemGroup>
              <ItemGroup>
                <Reference Include="AgbStudio.Api">
                  <HintPath>{IdeDir}/sdk/AgbStudio.Api.dll</HintPath>
                </Reference>
                <Analyzer Include="{IdeDir}/sdk/AgbStudio.Analyzers.dll" />
                <Analyzer Include="{IdeDir}/sdk/AgbStudio.Analyzers.CodeFixes.dll" />
              </ItemGroup>
            </Project>

            """;
        Put(Path.GetFileName(ProjectFile(root, projectName)), csproj);

        // Keeps the IDE build out of the repository folders above and its obj/ under build/ide.
        Put("Directory.Build.props", $"""
            <Project>
              <!-- Generated by AGB Studio: the IDE project's intermediate files go to {IdeDir}/obj. -->
              <PropertyGroup>
                <BaseIntermediateOutputPath>$(MSBuildThisFileDirectory){IdeDir}/obj/</BaseIntermediateOutputPath>
              </PropertyGroup>
            </Project>

            """);

        var editorconfig = new StringBuilder("# Generated by AGB Studio from Project Settings · Scripting.\nroot = true\n\n[*.cs]\n");
        foreach (var id in new[] { "GAE001", "GAE002", "GAE003", "GAE004", "GAE005", "GAE006" })
        {
            var sev = ctx.Analyzer.Rules.TryGetValue(id, out var r) ? r : DefaultSeverity(id);
            var text = sev switch { RuleSeverity.None => "none", RuleSeverity.Info => "suggestion", RuleSeverity.Warning => "warning", _ => "error" };
            editorconfig.Append($"dotnet_diagnostic.{id}.severity = {text}\n");
        }
        Put(".editorconfig", editorconfig.ToString());

        var settings = new Dictionary<string, object>
        {
            ["dotnet.defaultSolution"] = "disable",
            ["dotnet.backgroundAnalysis.analyzerDiagnosticsScope"] = "openFiles",
            ["omnisharp.enableRoslynAnalyzers"] = true,
            ["omnisharp.enableEditorConfigSupport"] = true,
            ["files.associations"] = new Dictionary<string, string> { ["*.graph"] = "json", ["*.dlg"] = "json", ["*.scene"] = "json", ["*.agbproj"] = "json" },
            ["files.exclude"] = new Dictionary<string, bool> { ["build/"] = true, ["Directory.Build.props"] = true },
        };
        var json = new JsonSerializerOptions { WriteIndented = true };
        Put(".vscode/settings.json", JsonSerializer.Serialize(settings, json) + "\n");
        Put(".vscode/extensions.json", JsonSerializer.Serialize(new { recommendations = new[] { "ms-dotnettools.csharp" } }, json) + "\n");
        return written;
    }

    static RuleSeverity DefaultSeverity(string id) => id is "GAE001" or "GAE004" ? RuleSeverity.Error : RuleSeverity.Warning;
}
