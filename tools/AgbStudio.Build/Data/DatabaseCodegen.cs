using System.Globalization;
using System.Text;
using AgbStudio.Build.Pipeline;
using AgbStudio.Core.Project;

namespace AgbStudio.Build.Data;

/// <summary>Database tables (T-P07) as const data in ROM with typed access: a table "Items" becomes
/// <c>agb_db::Items::Get(agb_db::ItemId::Potion)</c> returning <c>const agb_db::Item&amp;</c>.</summary>
public static class DatabaseCodegen
{
    // Items -> Item, Enemies -> Enemy, Heroes -> Hero, Bosses -> Boss, Boxes -> Box, Glass stays.
    public static string Singular(string table) =>
        table.EndsWith("ies", StringComparison.Ordinal) && table.Length > 3 ? table[..^3] + "y"
        : table.EndsWith("ses", StringComparison.Ordinal) || table.EndsWith("xes", StringComparison.Ordinal) || table.EndsWith("oes", StringComparison.Ordinal) ||
          table.EndsWith("ches", StringComparison.Ordinal) || table.EndsWith("shes", StringComparison.Ordinal) ? table[..^2]
        : table.EndsWith('s') && !table.EndsWith("ss", StringComparison.Ordinal) && table.Length > 1 ? table[..^1] : table;

    public static string IdEnum(string table) => Cpp.Ident(Singular(table)) + "Id";

    // The row struct: the singular name ("Items" -> Item), or "<Table>Row" when the table name has no plural
    // (a "Dialogue" table would otherwise give the row and the table class the same name).
    public static string RowStruct(string table) => Cpp.Ident(Singular(table)) is var s && s == Cpp.Ident(table) ? s + "Row" : s;

    public static string CppType(FieldDef f, string structName) => f.Type switch
    {
        "int" => "int",
        "fixed" => "agb::fixed",
        "bool" => "bool",
        "text" => f.Localized ? "unsigned short" : "const char*",
        "enum" => $"{structName}{Cpp.Ident(Capital(f.Name))}",
        "sprite" => "const agb::data::SpriteSheet*",
        "sound" => "unsigned short",
        "script" => "void (*)()",
        "reference" => "unsigned short",
        _ => "int",
    };

    /// <summary>Bytes per row in ROM, as shown by Add Field ("Per row · 1 B").</summary>
    public static int FieldBytes(FieldDef f) => f.Type switch
    {
        "bool" or "enum" => 1,
        "sound" or "reference" => 2,
        "text" => f.Localized ? 2 : 4,
        _ => 4,
    };

    /// <summary>The order of the fields in the row struct: 4-byte fields, then 2-byte, then 1-byte ones, so the struct
    /// has no padding between fields (only at the end, up to its alignment).</summary>
    public static List<FieldDef> RowFields(TableFile t) => t.Fields.Where(f => f.Name != t.KeyField).OrderByDescending(FieldBytes).ToList();

    /// <summary>sizeof the row struct in the ROM: the field bytes rounded up to the largest field.</summary>
    public static int RowBytes(TableFile t)
    {
        var fields = RowFields(t);
        if (fields.Count == 0) return 1;
        var align = fields.Max(FieldBytes);
        return (fields.Sum(FieldBytes) + align - 1) / align * align;
    }

    /// <summary>Bytes of the whole table in the ROM (an empty table still has one row).</summary>
    public static int TableBytes(TableFile t) => Math.Max(1, t.Rows.Count) * RowBytes(t);

    static string Capital(string s) => s.Length == 0 ? s : char.ToUpperInvariant(s[0]) + s[1..];

    public sealed class Output
    {
        public string Header { get; set; } = "";
        public List<(string File, string Text)> Sources { get; } = new();
        public int RomBytes { get; set; }
    }

    /// <summary>The function a "script" cell compiles to (defined by the scripting compiler's registry).</summary>
    public static string ScriptCellSymbol(string table, string rowId, string field) =>
        $"agb_dbscript_{Cpp.Ident(table)}_{Cpp.Ident(rowId)}_{Cpp.Ident(field)}";

    /// <summary>The code of a "script" cell; empty cells (and defaults) have none.</summary>
    public static string ScriptCellCode(Dictionary<string, string> row, FieldDef f) => (row.GetValueOrDefault(f.Name) ?? "").Trim();

    /// <param name="scriptCells">The scripting compiler runs in this build and defines the functions of the "script"
    /// cells; the table points at them. Without it script cells are null.</param>
    public static Output Generate(IReadOnlyList<TableFile> tables, Func<string, int> stringKey, Func<string, int> soundId,
        Func<string, bool> spriteExists, List<Diagnostic> diags, string dataDir, bool scriptCells = false)
    {
        var o = new Output();
        var h = new StringBuilder();
        h.Append("// Generated by AGB Studio from data/*.db. Do not edit.\n#pragma once\n#include \"agb/data.hpp\"\n#include \"agb/fixed.hpp\"\n\n");
        foreach (var t in tables.Where(t => t.Fields.Any(f => f.Type == "sprite"))) _ = t;
        h.Append("namespace agb_db {\n");
        // C# Items.Get(ItemId.Potion).effect(): runs a script cell; an empty cell does nothing.
        h.Append("inline void Run(void (*cell)()) {\n    if (cell) cell();\n}\n");
        foreach (var t in tables)
        {
            var st = RowStruct(t.Name);
            var ids = t.Rows.Select(r => r.GetValueOrDefault(t.KeyField) ?? "").ToList();
            h.Append($"enum class {IdEnum(t.Name)} : unsigned short {{ ");
            h.Append(string.Join(", ", ids.Select(i => Cpp.Ident(i))));
            h.Append(ids.Count > 0 ? ", Count };\n" : "Count };\n");
            foreach (var f in t.Fields.Where(f => f.Type == "enum" && f.Name != t.KeyField))
                h.Append($"enum class {st}{Cpp.Ident(Capital(f.Name))} : unsigned char {{ {string.Join(", ", f.EnumValues.Select(Cpp.Ident))} }};\n");
            h.Append($"struct {st} {{\n");
            foreach (var f in RowFields(t))
                h.Append(f.Type == "script" ? $"    void (*{Cpp.Ident(f.Name)})();\n" : $"    {CppType(f, st)} {Cpp.Ident(f.Name)};\n");
            if (t.Fields.All(f => f.Name == t.KeyField)) h.Append("    unsigned char unused;\n");
            h.Append("};\n");
            h.Append($"extern const {st} agbdata_{Cpp.Ident(t.Name)}[];\n");
            h.Append($"struct {Cpp.Ident(t.Name)} {{\n");
            h.Append($"    static const {st}& Get({IdEnum(t.Name)} id) {{ return agbdata_{Cpp.Ident(t.Name)}[static_cast<unsigned short>(id)]; }}\n");
            h.Append($"    static int Count() {{ return {ids.Count}; }}\n}};\n\n");

            var sb = new StringBuilder();
            sb.Append("// Generated by AGB Studio from ").Append(t.Name).Append(".db. Do not edit.\n#include \"agb_db.hpp\"\n");
            var file = Path.Combine(dataDir, t.Name + ".db");
            foreach (var f in t.Fields.Where(f => f.Type == "sprite"))
                foreach (var name in t.Rows.Select(r => r.GetValueOrDefault(f.Name) ?? "").Where(n => n.Length > 0 && spriteExists(n)).Distinct())
                    sb.Append($"extern const agb::data::SpriteSheet agbasset_sprite_{Cpp.Ident(name)};\n");
            if (scriptCells)
                foreach (var f in t.Fields.Where(f => f.Type == "script"))
                    foreach (var row in t.Rows.Where(r => ScriptCellCode(r, f).Length > 0))
                        sb.Append($"void {ScriptCellSymbol(t.Name, row.GetValueOrDefault(t.KeyField) ?? "", f.Name)}();\n");
            sb.Append($"namespace agb_db {{\nextern const {st} agbdata_{Cpp.Ident(t.Name)}[] = {{\n");
            for (var ri = 0; ri < t.Rows.Count; ri++)
            {
                var row = t.Rows[ri];
                var values = new List<string>();
                foreach (var f in RowFields(t))
                {
                    if (f.Type == "script")
                    {
                        // Script cells ("score += 10", "Heal(power)") are compiled by the scripting compiler (P9.06).
                        values.Add(scriptCells && ScriptCellCode(row, f).Length > 0 ? "&" + ScriptCellSymbol(t.Name, ids[ri], f.Name) : "nullptr");
                        continue;
                    }
                    var raw = row.GetValueOrDefault(f.Name);
                    if (string.IsNullOrWhiteSpace(raw)) raw = f.Default;
                    values.Add(Value(f, st, raw ?? "", stringKey, soundId, spriteExists, tables, d => diags.Add(new Diagnostic(Severity.Warning, file, 0, 0, "",
                        $"{t.Name} row {ri + 1} ({ids[ri]}), {f.Name}: {d}"))));
                }
                if (values.Count == 0) values.Add("0");
                sb.Append($"    {{{string.Join(", ", values)}}},\n");
            }
            if (t.Rows.Count == 0) sb.Append($"    {{}},\n");
            sb.Append("};\n}  // namespace agb_db\n");
            o.Sources.Add(($"db_{Cpp.Ident(t.Name)}.cpp", sb.ToString()));
            o.RomBytes += TableBytes(t);
        }
        h.Append("}  // namespace agb_db\n");
        o.Header = h.ToString();
        return o;
    }

    static string Value(FieldDef f, string st, string raw, Func<string, int> stringKey, Func<string, int> soundId, Func<string, bool> spriteExists,
        IReadOnlyList<TableFile> tables, Action<string> warn)
    {
        raw = raw.Trim();
        switch (f.Type)
        {
            case "int":
                if (raw.Length == 0) return "0";
                if (int.TryParse(raw, NumberStyles.Integer, CultureInfo.InvariantCulture, out var i)) return i.ToString(CultureInfo.InvariantCulture);
                warn($"'{raw}' is not a whole number; using 0.");
                return "0";
            case "fixed":
                if (raw.Length == 0) return "agb::fixed()";
                if (double.TryParse(raw, NumberStyles.Float, CultureInfo.InvariantCulture, out var d)) return Cpp.Fixed(d);
                warn($"'{raw}' is not a number; using 0.");
                return "agb::fixed()";
            case "bool":
                return raw.Equals("true", StringComparison.OrdinalIgnoreCase) || raw.Equals("yes", StringComparison.OrdinalIgnoreCase) || raw == "1" ? "true" : "false";
            case "text":
                if (!f.Localized) return Cpp.Str(raw);
                var key = stringKey(raw);
                if (key < 0 && raw.Length > 0) warn($"string key '{raw}' is not in the Localization tables, so the first string is used. Add the key in Localization, or fix the cell in Database.");
                return Math.Max(0, key).ToString(CultureInfo.InvariantCulture);
            case "enum":
                var idx = f.EnumValues.IndexOf(raw);
                if (idx < 0)
                {
                    if (raw.Length > 0) warn($"'{raw}' is not one of {string.Join(", ", f.EnumValues)}; using {f.EnumValues.FirstOrDefault() ?? "0"}.");
                    idx = 0;
                }
                return f.EnumValues.Count == 0 ? "{}" : $"{st}{Cpp.Ident(Capital(f.Name))}::{Cpp.Ident(f.EnumValues[idx])}";
            case "sprite":
                if (raw.Length == 0) return "nullptr";
                if (!spriteExists(raw)) { warn($"sprite '{raw}' is not in assets/sprites, so no sprite is used. Import the sprite, or fix the cell in Database."); return "nullptr"; }
                return $"&agbasset_sprite_{Cpp.Ident(raw)}";
            case "sound":
                return Math.Max(0, soundId(raw)).ToString(CultureInfo.InvariantCulture);
            case "script":
                // Script cells ("score += 10", "Heal(power)") are compiled by the scripting compiler.
                return "nullptr";
            case "reference":
                var target = tables.FirstOrDefault(t => t.Name == f.Reference);
                var ri = target?.Rows.FindIndex(r => r.GetValueOrDefault(target.KeyField) == raw) ?? -1;
                if (ri < 0 && raw.Length > 0) warn($"'{raw}' is not a row of {f.Reference}, so its first row is used. Pick an existing row in the cell in Database.");
                return Math.Max(0, ri).ToString(CultureInfo.InvariantCulture);
            default:
                return "0";
        }
    }
}

/// <summary>Import CSV (T-D19): map columns to fields, check types, report problem rows with defaults.</summary>
public static class CsvImporter
{
    public sealed record Mapping(string Column, string? Field);  // Field null = "— skip —"

    public sealed record Result(List<Dictionary<string, string>> Rows, List<string> Warnings, List<string> Columns);

    public static List<string[]> Parse(string text)
    {
        var rows = new List<string[]>();
        var row = new List<string>();
        var cell = new StringBuilder();
        var quoted = false;
        for (var i = 0; i < text.Length; i++)
        {
            var c = text[i];
            if (quoted)
            {
                if (c == '"' && i + 1 < text.Length && text[i + 1] == '"') { cell.Append('"'); i++; }
                else if (c == '"') quoted = false;
                else cell.Append(c);
                continue;
            }
            switch (c)
            {
                case '"': quoted = true; break;
                case ',': row.Add(cell.ToString()); cell.Clear(); break;
                case '\r': break;
                case '\n':
                    row.Add(cell.ToString());
                    cell.Clear();
                    if (row.Count > 1 || row[0].Length > 0) rows.Add(row.ToArray());
                    row.Clear();
                    break;
                default: cell.Append(c); break;
            }
        }
        if (cell.Length > 0 || row.Count > 0)
        {
            row.Add(cell.ToString());
            rows.Add(row.ToArray());
        }
        return rows;
    }

    /// <summary>Guesses the field for each column by name (Name_EN -> name, Cost -> price ...).</summary>
    public static List<Mapping> AutoMap(IReadOnlyList<string> columns, TableFile table) =>
        columns.Select(c =>
        {
            var norm = c.ToLowerInvariant().Replace("_", "").Replace(" ", "");
            var f = table.Fields.FirstOrDefault(f => f.Name.Equals(c, StringComparison.OrdinalIgnoreCase) || norm.StartsWith(f.Name.ToLowerInvariant(), StringComparison.Ordinal))
                    ?? (norm is "cost" ? table.Fields.FirstOrDefault(f => f.Name == "price") : null)
                    ?? (norm.EndsWith("id", StringComparison.Ordinal) ? table.Fields.FirstOrDefault(f => f.Name == table.KeyField) : null);
            return new Mapping(c, f?.Name);
        }).ToList();

    public static Result Import(string csvText, TableFile table, IReadOnlyList<Mapping>? mapping = null)
    {
        var parsed = Parse(csvText);
        if (parsed.Count == 0) return new Result(new(), new() { "The CSV file is empty." }, new());
        var columns = parsed[0].ToList();
        mapping ??= AutoMap(columns, table);
        var rows = new List<Dictionary<string, string>>();
        var problems = new Dictionary<string, List<int>>();
        for (var r = 1; r < parsed.Count; r++)
        {
            var row = new Dictionary<string, string>();
            for (var c = 0; c < columns.Count && c < parsed[r].Length; c++)
            {
                var field = mapping.FirstOrDefault(m => m.Column == columns[c])?.Field;
                if (field == null) continue;
                var def = table.Fields.First(f => f.Name == field);
                var value = parsed[r][c].Trim();
                if (def.Name != table.KeyField && !Valid(def, value))
                {
                    var key = $"{columns[c]} is “{value}”";
                    if (!problems.TryGetValue(key, out var list)) problems[key] = list = new List<int>();
                    list.Add(r);
                    value = def.Default;
                }
                if (row.TryGetValue(field, out var existing) && def.Localized) value = existing;  // first language column wins
                row[field] = value;
            }
            rows.Add(row);
        }
        var warnings = new List<string>();
        foreach (var (what, list) in problems)
        {
            var def = "default";
            var col = what[..what.IndexOf(" is ", StringComparison.Ordinal)];
            var field = mapping.First(m => m.Column == col).Field!;
            var fd = table.Fields.First(f => f.Name == field);
            def = string.IsNullOrEmpty(fd.Default) ? (fd.Type is "int" or "fixed" ? "0" : "empty") : fd.Default;
            var rowsText = list.Count == 1 ? $"Row {list[0]}" : $"Rows {string.Join(", ", list.Take(list.Count - 1))} and {list[^1]}";
            // Figma T-D19's wording; the Check column marks the field and the footer says the rows keep the default
            warnings.Add($"{rowsText}: {what} — will use the default {def}.");
        }
        return new Result(rows, warnings, columns);
    }

    static bool Valid(FieldDef f, string v) => f.Type switch
    {
        "int" => v.Length == 0 || int.TryParse(v, NumberStyles.Integer, CultureInfo.InvariantCulture, out _),
        "fixed" => v.Length == 0 || double.TryParse(v, NumberStyles.Float, CultureInfo.InvariantCulture, out _),
        "bool" => v.Length == 0 || v is "true" or "false" or "yes" or "no" or "1" or "0" || v.Equals("TRUE", StringComparison.Ordinal) || v.Equals("FALSE", StringComparison.Ordinal),
        "enum" => v.Length == 0 || f.EnumValues.Contains(v),
        _ => true,
    };
}
