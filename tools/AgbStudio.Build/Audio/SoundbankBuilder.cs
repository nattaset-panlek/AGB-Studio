using System.Globalization;
using System.Text;
using System.Text.RegularExpressions;
using AgbStudio.Build.Audio.Maxmod;
using AgbStudio.Core.Project;

namespace AgbStudio.Build.Audio;

public sealed record SoundbankResult(bool Success, string CppPath, string HeaderPath, IReadOnlyDictionary<string, int> Ids, string Log)
{
    /// <summary>The MusicMeta of each module as built into the ROM, by module id.</summary>
    public IReadOnlyList<BuiltMusic> Music { get; init; } = [];
}

/// <summary>
/// A module's <see cref="MusicMeta"/> as the ROM has it: volume 0..256 (agb::audio::MusicInfo), the loop start clamped to
/// the module's orders (written into the module as maxmod's restart order) and fade on scene change.
/// </summary>
public sealed record BuiltMusic(string File, int Orders, int Volume, int LoopStart, bool FadeOnSceneChange);

/// <summary>Converts MOD / XM / S3M / IT / WAV files to a maxmod soundbank (AGB Studio's C# port of mmutil 1.10.1, P24.05)
/// and embeds it as C++.</summary>
public static class SoundbankBuilder
{
    /// <summary>
    /// Makes the soundbank of <paramref name="inputs"/> as mmutil 1.10.1 does (byte for byte, MaxmodSoundbankTests). Each module's <c>&lt;file&gt;.meta.json</c> (MusicMeta, defaults when
    /// absent) goes into the ROM: the loop start becomes the module's restart order (maxmod continues there when a
    /// looping song ends), and volume and fade on scene change go into the table <c>&lt;symbol&gt;_music</c>
    /// (agb::audio::MusicInfo by module id).
    /// </summary>
    public static SoundbankResult Build(IReadOnlyList<string> inputs, string outDir, string symbol = "agb_soundbank")
    {
        Directory.CreateDirectory(outDir);
        var bin = Path.Combine(outDir, "soundbank.bin");
        var mmHeader = Path.Combine(outDir, "soundbank_mm.h");
        if (File.Exists(bin)) File.Delete(bin);
        var r = MaxmodSoundbank.Write(inputs.Select(Path.GetFullPath).ToList(), bin, mmHeader);
        if (!r.Success || !File.Exists(bin))
            return new SoundbankResult(false, "", "", new Dictionary<string, int>(), r.Log);

        var ids = new Dictionary<string, int>();
        // the header is written in the ANSI code page, as mmutil does; the names are ASCII apart from file names that are not
        foreach (Match m in Regex.Matches(File.ReadAllText(mmHeader, Encoding.Latin1), @"#define\s+(\w+)\s+(\d+)"))
            ids[m.Groups[1].Value] = int.Parse(m.Groups[2].Value, CultureInfo.InvariantCulture);

        var data = File.ReadAllBytes(bin);
        var music = ApplyMusicMeta(data, inputs, ids);
        File.WriteAllBytes(bin, data);  // the soundbank as the ROM has it (loop starts written)
        var cpp = Path.Combine(outDir, "soundbank.cpp");
        var hpp = Path.Combine(outDir, "soundbank.hpp");
        WriteIfChanged(cpp, BinaryToCpp(data, symbol) + MusicTableCpp(music, symbol));
        var h = new StringBuilder();
        h.AppendLine("// Generated by AGB Studio from its maxmod soundbank. Do not edit.");
        h.AppendLine("#pragma once");
        h.AppendLine("#include \"agb/audio.hpp\"");
        h.AppendLine($"extern const unsigned char {symbol}[];");
        h.AppendLine($"// MusicMeta by module id; {music.Count} module(s).");
        h.AppendLine($"extern const agb::audio::MusicInfo {symbol}_music[];");
        h.AppendLine($"constexpr unsigned short {symbol}_music_count = {music.Count};");
        h.AppendLine("namespace agb_sound {");
        foreach (var (name, id) in ids.OrderBy(k => k.Value).ThenBy(k => k.Key, StringComparer.Ordinal))
            h.AppendLine($"constexpr unsigned short {name} = {id};");
        h.AppendLine("}  // namespace agb_sound");
        WriteIfChanged(hpp, h.ToString());
        return new SoundbankResult(true, cpp, hpp, ids, r.Log) { Music = music };
    }

    static bool IsModule(string f) => GameProject.MusicExtensions.Contains(Path.GetExtension(f).ToLowerInvariant());

    /// <summary>The meta files the soundbank reads (part of its cache key).</summary>
    public static IEnumerable<string> MetaFiles(IEnumerable<string> inputs) => inputs.Where(IsModule).Select(GameProject.MetaPath).Where(File.Exists);

    /// <summary>The MusicMeta of a module file, or the defaults the Audio page shows when it has none.</summary>
    public static MusicMeta MetaOf(string module) =>
        File.Exists(GameProject.MetaPath(module)) ? GameProject.Load<MusicMeta>(GameProject.MetaPath(module)) : new MusicMeta();

    // The soundbank (maxmod MSL): u16 sample count, u16 module count, "*maxmod*", then one u32 offset per sample and per
    // module. A module entry is an 8-byte prefix and the MAS header: order count at +8, restart order at +16.
    static List<BuiltMusic> ApplyMusicMeta(byte[] bank, IReadOnlyList<string> inputs, IReadOnlyDictionary<string, int> ids)
    {
        if (bank.Length < 12 || Encoding.ASCII.GetString(bank, 4, 8) != "*maxmod*")
            throw new InvalidDataException("The soundbank has no *maxmod* header, so AGB Studio cannot read it. This is a bug in AGB Studio: report it with the audio files of the build.");
        int samples = BitConverter.ToUInt16(bank, 0), modules = BitConverter.ToUInt16(bank, 2);
        var files = new string?[modules];
        var unnamed = new Queue<string>();
        foreach (var f in inputs.Where(IsModule))
        {
            // mmutil names a module MOD_ + its file name in capitals, other characters as '_'
            var key = "MOD_" + Regex.Replace(Path.GetFileNameWithoutExtension(f).ToUpperInvariant(), "[^A-Z0-9]", "_");
            if (ids.TryGetValue(key, out var id) && id < modules && files[id] == null) files[id] = f;
            else unnamed.Enqueue(f);
        }
        for (var id = 0; id < modules; id++) files[id] ??= unnamed.Count > 0 ? unnamed.Dequeue() : null;
        var result = new List<BuiltMusic>();
        for (var id = 0; id < modules; id++)
        {
            var at = (int)BitConverter.ToUInt32(bank, 12 + 4 * (samples + id));
            int orders = bank[at + 8];
            var meta = files[id] is { } f ? MetaOf(f) : new MusicMeta();
            var loop = Math.Clamp(meta.LoopStart, 0, Math.Max(0, orders - 1));
            bank[at + 16] = (byte)loop;
            var volume = (int)Math.Round(Math.Clamp(meta.Volume, 0, 1) * 256);
            result.Add(new BuiltMusic(files[id] ?? "", orders, volume, loop, meta.FadeOnSceneChange));
        }
        return result;
    }

    static string MusicTableCpp(IReadOnlyList<BuiltMusic> music, string symbol)
    {
        var sb = new StringBuilder();
        sb.AppendLine("#include \"agb/audio.hpp\"");
        sb.AppendLine("// MusicMeta of each module by module id: volume (0..256), loop start (order), fade on scene change.");
        sb.AppendLine($"extern const agb::audio::MusicInfo {symbol}_music[] = {{");
        foreach (var m in music)
            sb.AppendLine($"    {{{m.Volume}, {m.LoopStart}, {(m.FadeOnSceneChange ? "true" : "false")}}},  // {Path.GetFileName(m.File)}");
        if (music.Count == 0) sb.AppendLine("    {256, 0, true},  // no music: one entry, the count is 0");
        sb.AppendLine("};");
        return sb.ToString();
    }

    public static string BinaryToCpp(byte[] data, string symbol)
    {
        var sb = new StringBuilder(data.Length * 5 + 200);
        sb.AppendLine("// Generated by AGB Studio. Do not edit.");
        sb.AppendLine($"alignas(4) extern const unsigned char {symbol}[] = {{");
        for (var i = 0; i < data.Length; i++)
        {
            sb.Append(data[i]).Append(',');
            if (i % 32 == 31) sb.AppendLine();
        }
        sb.AppendLine("};");
        sb.AppendLine($"extern const unsigned int {symbol}_size = {data.Length};");
        return sb.ToString();
    }

    public static void WriteIfChanged(string path, string text)
    {
        if (File.Exists(path) && File.ReadAllText(path) == text) return;
        Directory.CreateDirectory(Path.GetDirectoryName(path)!);
        File.WriteAllText(path, text);
    }
}
