using System.Text;
using AgbStudio.Editor.Tests.Support;
using Avalonia.Headless.XUnit;

namespace AgbStudio.Editor.Tests.Prototype;

/// <summary>
/// T-X03: every prototype click link of "AGB Studio · Screens" goes to the same window in the app; every Cancel / Close
/// closes its overlay; tabs and Stop lead back. The link list is read from the read-only Figma export at test time
/// (docs/evidence/figma/prototype.json) and each link is one E2E case: open its source window in the headless app,
/// click the app control of the linked node, check the result.
/// </summary>
[Collection(EmulatorCollection.Name)]
public class PrototypeLinkTests
{
    public static IEnumerable<object[]> Cases() => PrototypeData.Links.Select(l => new object[] { l.Index, l.ToString() });

    [Fact]
    public void Export_HasTheTwoFlowsAnd120Links_EveryFrameIsAWindow_EveryNodeHasAnAppControl()
    {
        Assert.Equal(120, PrototypeData.Links.Count);
        Assert.Equal([("AGB Studio · start", "T-P12"), ("AGB Studio · editor", "T-P01")], PrototypeData.Flows.Select(f => (f.Name, f.StartId)));
        foreach (var l in PrototypeData.Links)
        {
            Assert.Equal("ON_CLICK", l.Trigger);
            Assert.Contains(l.Action, new[] { "NAVIGATE", "OVERLAY", "CLOSE", "SWAP", "BACK" });
            Assert.NotNull(AppSession.TypeOf(l.FromId));
            if (l.ToId != null) Assert.NotNull(AppSession.TypeOf(l.ToId));
            Assert.True(LinkControls.For(l) != null, $"{l}: no app control is known for this node");
        }
        WriteEvidence();
    }

    [AvaloniaTheory]
    [MemberData(nameof(Cases))]
    public void T_X03_Link_LeadsToTheSameWindowInTheApp(int index, string link)
    {
        var l = PrototypeData.Links[index];
        Assert.Equal(link, l.ToString());
        using var s = new AppSession(project: !AppSession.BeforeProject(l.FromId), light: l.FromId is "T-L02" or "T-L03");
        s.OpenSource(l.FromId);
        LinkRunner.Follow(s, l);
    }

    /// <summary>docs/evidence/prototype-links.md: each Figma link with the app control the E2E case clicks.</summary>
    static void WriteEvidence()
    {
        var md = new StringBuilder();
        md.Append("# Prototype links (T-X01..T-X03)\n\n");
        md.Append("Generated by `PrototypeLinkTests` (tests/AgbStudio.Editor.Tests/Prototype) from the read-only Figma export ")
          .Append("`docs/evidence/figma/prototype.json`: ").Append(PrototypeData.Links.Count).Append(" click links of \"AGB Studio · Screens\" ")
          .Append("and ").Append(PrototypeData.Flows.Count).Append(" flows. Each link is one E2E case ")
          .Append("(`PrototypeLinkTests.T_X03_Link_LeadsToTheSameWindowInTheApp`): the source window is opened in the headless app, ")
          .Append("the app control below is clicked, and the result is checked (NAVIGATE: the destination page is shown; ")
          .Append("OVERLAY: the destination opens on top; CLOSE: the dialog or popover closes). ")
          .Append("`PrototypeFlowTests` follows each flow from its start frame through every link it reaches.\n\n");
        md.Append("| # | From | Figma node | Action | To | App control |\n|---|---|---|---|---|---|\n");
        foreach (var l in PrototypeData.Links)
        {
            var c = LinkControls.For(l)!;
            md.Append($"| {l.Index} | {l.FromId} {l.From} | {l.Node} | {l.Action} | {(l.ToId is null ? "" : l.ToId + " " + l.To)} | {c.Name}{(c.Differs is null ? "" : " (see below)")} |\n");
        }
        var differs = PrototypeData.Links.Select(l => (l, c: LinkControls.For(l)!)).Where(x => x.c.Differs != null).ToList();
        md.Append("\n## Links whose app control is not the Figma node\n\n");
        if (differs.Count == 0) md.Append("None.\n");
        foreach (var g in differs.GroupBy(x => x.c.Differs))
            md.Append("- ").Append(string.Join(", ", g.Select(x => "#" + x.l.Index))).Append(": ").Append(g.Key).Append('\n');
        md.Append("\nTriggers: every link is ON_CLICK. Asset Card links are double-clicked in the app, as Editor Map #24 says ")
          .Append("(\"Asset (double-click)\"); Figma prototypes have no double-click trigger.\n");
        md.Append("\nDialog Footer › Cancel of About and Keyboard Shortcuts: both show one footer button, Close, in Figma and in the app ")
          .Append("(the footer's Cancel instance, where Figma put the link, is hidden in the frame); the test clicks Close.\n");
        md.Append("\n## Flows (T-X01, T-X02)\n\n");
        foreach (var f in PrototypeData.Flows)
        {
            var reach = PrototypeData.Reachable(f.StartId);
            var windows = reach.Select(l => l.FromId).Distinct().ToList();
            // pages of the flow with no chain of links back to the start: the walk restarts the flow there
            bool Back(string page)
            {
                var seen = new HashSet<string> { page };
                var queue = new Queue<string>([page]);
                while (queue.Count > 0)
                {
                    var at = queue.Dequeue();
                    if (at == f.StartId) return true;
                    foreach (var l in reach.Where(l => l.FromId == at && l.Action == "NAVIGATE" && l.ToId != null))
                        if (seen.Add(l.ToId!)) queue.Enqueue(l.ToId!);
                }
                return false;
            }
            var deadEnds = reach.Where(l => l.Action == "NAVIGATE").Select(l => l.ToId!).Distinct().Where(p => !Back(p)).ToList();
            md.Append($"- \"{f.Name}\" starts on {f.StartId} {f.Start}: {reach.Count} links in {windows.Count} windows. ")
              .Append(deadEnds.Count == 0 ? "Every page has links back to the start.\n"
                  : $"No link leads back from {string.Join(", ", deadEnds.Select(p => p + " " + PrototypeData.Frames.First(kv => kv.Value == p).Key))}; the walk restarts the flow there, as the Figma presenter does.\n");
        }
        File.WriteAllText(Path.Combine(Repo.Evidence, "prototype-links.md"), md.ToString());
    }
}
